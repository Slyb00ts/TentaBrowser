#!/usr/bin/env python3
"""Generates src/names.rs from checklist/methods.toml.

Usage: python3 crates/tenta-cdp/checklist/gen_names.py

The checklist records names and clients, not parameter schemas, so only the
name tables are generated. A unit test in names.rs fails when the checked-in
file and the checklist disagree.
"""

import pathlib
import tomllib

root = pathlib.Path(__file__).resolve().parent.parent
entries = tomllib.loads((root / "checklist" / "methods.toml").read_text())["entry"]


def table(kind):
    return sorted({e["name"] for e in entries if e["kind"] == kind})


lines = [
    "//! Method and event names the reference clients use.",
    "//!",
    "//! Generated by `checklist/gen_names.py` from `checklist/methods.toml`; do not",
    "//! edit by hand.",
    "",
]
for const, doc, kind in (
    ("METHODS", "Commands Puppeteer or Playwright send, sorted.", "method"),
    ("EVENTS", "Events Puppeteer or Playwright listen for, sorted.", "event"),
):
    lines.append(f"/// {doc}")
    lines.append(f"pub const {const}: &[&str] = &[")
    lines.extend(f'    "{name}",' for name in table(kind))
    lines.append("];")
    lines.append("")
lines.extend(
    [
        "#[cfg(test)]",
        "mod tests {",
        "    use super::*;",
        "",
        "    fn checklist(kind: &str) -> Vec<String> {",
        "        let text = include_str!(\"../checklist/methods.toml\");",
        "        let mut names = Vec::new();",
        "        let mut current = None;",
        "        for line in text.lines() {",
        "            if let Some(name) = line.strip_prefix(\"name = \\\"\") {",
        "                current = name.strip_suffix('\"');",
        "            } else if line == format!(\"kind = \\\"{kind}\\\"\") {",
        "                names.extend(current.map(str::to_owned));",
        "            }",
        "        }",
        "        names.sort();",
        "        names.dedup();",
        "        names",
        "    }",
        "",
        "    #[test]",
        "    fn tables_match_the_checklist() {",
        "        assert_eq!(METHODS, checklist(\"method\"), \"run checklist/gen_names.py\");",
        "        assert_eq!(EVENTS, checklist(\"event\"), \"run checklist/gen_names.py\");",
        "    }",
        "}",
        "",
    ]
)
(root / "src" / "names.rs").write_text("\n".join(lines))
