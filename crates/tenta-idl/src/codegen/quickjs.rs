//! Native QuickJS bindings. All interfaces share one branded host class so an
//! inherited operation accepts a derived wrapper without trusting its prototype.

use crate::codegen::rust_type::{Position, float_literal, integer_suffix, rust_type};
use crate::model::{
    Argument, Attribute, ConstValue, Constant, FastApi, Interface, Member, Model, Namespace,
    Operation, OperationGroup, Type,
};
use crate::naming;
use std::fmt::Write as _;

/// Generates the native QuickJS installer for one interface.
pub fn interface_quickjs(model: &Model, interface: &Interface) -> String {
    let name = &interface.name;
    let snake = naming::snake_stem(name);
    let length = interface.constructor_length().unwrap_or(0);
    let mut bound = format!("{name}Ops");
    if !interface.constructors.is_empty() {
        bound.push_str(&format!(" + {name}Constructor"));
    }
    let mut out = format!(
        "// Native QuickJS bindings for `{name}`. Generated by `tenta-idl`; do not edit.\n\npub fn install_{snake}<'js, T: {bound} + 'static>(ctx: &rquickjs::Ctx<'js>, global: &rquickjs::Object<'js>, registry: &mut dyn InterfaceRegistry) -> rquickjs::Result<()> {{\n    let prototype = rquickjs::Object::new(ctx.clone())?;\n"
    );
    if let Some(parent) = &interface.parent {
        let _ = writeln!(
            out,
            "    prototype.set_prototype(Some(&quickjs_prototype(ctx, {parent:?})?))?;"
        );
    }
    for constant in &interface.constants {
        constant_property(constant, "prototype", &mut out);
    }
    for member in &interface.members {
        match member {
            Member::Attribute(a) if !a.is_static => {
                accessor_property(model, a, name, "prototype", &mut out)
            }
            Member::Operation(g) if !g.is_static => {
                method_property(g, Some(name), "prototype", &mut out)
            }
            _ => {}
        }
    }
    if let Some(iterable) = &interface.iterable {
        if let Some(key) = &iterable.key {
            for (method, mode) in [("entries", 0), ("keys", 1), ("values", 2)] {
                let k = to_value(key, "&ctx", "key");
                let v = to_value(&iterable.value, "&ctx", "value");
                let _ = writeln!(
                    out,
                    "    prototype.set({method:?}, rquickjs::Function::new(ctx.clone(), |ctx: rquickjs::Ctx<'js>, this: rquickjs::function::This<rquickjs::Value<'js>>| {{ quickjs_callback_boundary(&ctx, {name:?}, || {{ let host = quickjs_host::<T>(&ctx, &this.0, {name:?})?; let pairs = host.iterable_entries().map_err(|e| throw_quickjs_error(&ctx, &e))?; let array = rquickjs::Array::new(ctx.clone())?; for (index, (key, value)) in pairs.into_iter().enumerate() {{ let key = {k}?; let value = {v}?; let item = match {mode} {{ 1 => key, 2 => value, _ => {{ let pair = rquickjs::Array::new(ctx.clone())?; quickjs_array_data_property(&pair, 0, key)?; quickjs_array_data_property(&pair, 1, value)?; pair.into_value() }} }}; quickjs_array_data_property(&array, index, item)?; }} quickjs_array_iterator(&ctx, array) }}) }})?)?;"
                );
            }
            out.push_str("    prototype.set(rquickjs::atom::PredefinedAtom::SymbolIterator, prototype.get::<_, rquickjs::Value>(\"entries\")?)?;\n");
        } else {
            out.push_str("    for method in [\"entries\", \"keys\", \"values\", \"forEach\"] { let array: rquickjs::Object = ctx.globals().get(\"Array\")?; let array_prototype: rquickjs::Object = array.get(\"prototype\")?; prototype.set(method, array_prototype.get::<_, rquickjs::Value>(method)?)?; }\n    prototype.set(rquickjs::atom::PredefinedAtom::SymbolIterator, prototype.get::<_, rquickjs::Value>(\"values\")?)?;\n");
        }
    }
    if super::legacy::has_indexed_iterator(model, interface) {
        // An indexed getter and an integer `length` iterate as an array does.
        out.push_str("    { let array: rquickjs::Object = ctx.globals().get(\"Array\")?; let array_prototype: rquickjs::Object = array.get(\"prototype\")?; prototype.prop(rquickjs::atom::PredefinedAtom::SymbolIterator, rquickjs::object::Property::from(array_prototype.get::<_, rquickjs::Value>(\"values\")?).writable().configurable())?; }\n");
    }
    let _ = writeln!(
        out,
        "    prototype.prop(rquickjs::atom::PredefinedAtom::SymbolToStringTag, rquickjs::object::Property::from({name:?}).configurable())?;"
    );
    let _ = writeln!(
        out,
        "    let constructor = rquickjs::function::Constructor::new_prototype_construct_only(ctx, prototype.clone(), |ctx: rquickjs::Ctx<'js>, target: rquickjs::Function<'js>, args: rquickjs::function::Rest<rquickjs::Value<'js>>| -> rquickjs::Result<(rquickjs::Value<'js>, rquickjs::Object<'js>)> {{ quickjs_callback_boundary(&ctx, {name:?}, || {{ quickjs_begin_stored_value_lease(&ctx)?;"
    );
    if let Some(constructor) = interface.constructors.first() {
        let passes = arguments(&constructor.arguments, false, &mut out);
        let mut args = vec!["&world_realm_quickjs(&ctx)?".to_owned()];
        args.extend(passes);
        let _ = writeln!(
            out,
            "        let resolved_prototype = quickjs_constructor_prototype(&ctx, &target, {name:?})?;\n        quickjs_before_constructor_host(&ctx)?;\n        let host = T::{}({}).map_err(|e| throw_quickjs_error(&ctx, &e))?;\n        quickjs_transfer_stored_value_lease(&ctx)?;\n        quickjs_adopt(&ctx, {name:?}, Box::new(host)).map(|object| (object.into_value(), resolved_prototype))",
            constructor.rust_name,
            args.join(", ")
        );
    } else {
        out.push_str(
            "        Err(rquickjs::Exception::throw_type(&ctx, \"Illegal constructor\"))\n",
        );
    }
    out.push_str("    }) })?;\n");
    let _ = writeln!(out, "    constructor.set_name({name:?})?;");
    let _ = writeln!(out, "    constructor.set_length({length})?;");
    if let Some(parent) = &interface.parent {
        let _ = writeln!(
            out,
            "    let parent_constructor: rquickjs::Function = global.get({parent:?})?;\n    constructor.set_prototype(Some(&parent_constructor))?;"
        );
    }
    for constant in &interface.constants {
        constant_property(constant, "constructor", &mut out);
    }
    for member in &interface.members {
        match member {
            Member::Attribute(a) if a.is_static => {
                accessor_property(model, a, name, "constructor", &mut out)
            }
            Member::Operation(g) if g.is_static => {
                method_property(g, None, "constructor", &mut out)
            }
            _ => {}
        }
    }
    legacy_properties(model, interface, &mut out);
    let ancestors = model
        .prototype_chain(name)
        .into_iter()
        .filter(|s| s != "Object")
        .map(|s| format!("{s:?}"))
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(
        out,
        "    quickjs_cache_prototype(ctx, {name:?}, prototype, &[{ancestors}])?;\n    global.prop({name:?}, rquickjs::object::Property::from(constructor).writable().configurable())?;\n    register_{snake}(registry);\n    Ok(())\n}}"
    );
    out
}

/// Generates the native QuickJS installer for one namespace.
pub fn namespace_quickjs(model: &Model, namespace: &Namespace) -> String {
    let name = &namespace.name;
    let snake = naming::snake_stem(name);
    let mut out = format!(
        "// Generated by `tenta-idl`; do not edit.\npub fn install_{snake}<'js, T: {name}Ops + 'static>(ctx: &rquickjs::Ctx<'js>, global: &rquickjs::Object<'js>, registry: &mut dyn InterfaceRegistry) -> rquickjs::Result<()> {{\n let namespace = rquickjs::Object::new(ctx.clone())?;\n"
    );
    for c in &namespace.constants {
        constant_property(c, "namespace", &mut out);
    }
    for m in &namespace.members {
        match m {
            Member::Attribute(a) => accessor_property(model, a, name, "namespace", &mut out),
            Member::Operation(g) => method_property(g, None, "namespace", &mut out),
        }
    }
    let _ = writeln!(
        out,
        " global.set({name:?}, namespace)?; register_{snake}(registry); Ok(())\n}}"
    );
    out
}

fn constant_property(constant: &Constant, target: &str, out: &mut String) {
    let value = match &constant.value {
        ConstValue::Boolean(v) => v.to_string(),
        ConstValue::Integer(v) => format!("{v}i64"),
        ConstValue::Float(v) => float_literal(*v),
        ConstValue::Null => "rquickjs::Null".into(),
    };
    let _ = writeln!(
        out,
        "    {target}.prop({:?}, rquickjs::object::Property::from({value}).enumerable())?;",
        constant.name
    );
}

fn accessor_property(
    model: &Model,
    a: &Attribute,
    interface: &str,
    target: &str,
    out: &mut String,
) {
    let receiver = if a.is_static {
        "T::".to_owned()
    } else {
        "host.".to_owned()
    };
    let this = if a.is_static {
        String::new()
    } else {
        ", this: rquickjs::function::This<rquickjs::Value<'js>>".to_owned()
    };
    let setup = if a.is_static {
        String::new()
    } else {
        format!("let host = quickjs_host::<T>(&ctx, &this.0, {interface:?})?;")
    };
    let getter = call(&format!("{receiver}{}()", a.getter_name), a.fast_getter);
    let conversion = to_value(&a.ty, "&ctx", "result");
    let get = format!(
        "|ctx: rquickjs::Ctx<'js>{this}| -> rquickjs::Result<rquickjs::Value<'js>> {{ quickjs_callback_boundary(&ctx, {:?}, || {{ {setup} let result = {getter}; {conversion} }}) }}",
        a.name
    );
    let accessor = if let Some(setter) = &a.setter_name {
        let conversion = super::convert::legacy_null_to_empty(
            &a.ty,
            &a.attrs,
            "value",
            from_value_for_attribute_setter(model, &a.ty, "&ctx", "value"),
        );
        let pass = borrow_expr(&a.ty, "value");
        let setter = call(
            &format!("{receiver}{setter}({pass})"),
            a.fast_setter.unwrap(),
        );
        format!(
            "rquickjs::object::Accessor::new({get}, |ctx: rquickjs::Ctx<'js>{this}, value: rquickjs::Value<'js>| -> rquickjs::Result<()> {{ quickjs_callback_boundary(&ctx, {:?}, || {{ {setup} let value = {conversion}?; {setter}; Ok(()) }}) }})",
            a.name
        )
    } else if let Some(forward) = a.put_forwards() {
        format!(
            "rquickjs::object::Accessor::new({get}, |ctx: rquickjs::Ctx<'js>{this}, value: rquickjs::Value<'js>| -> rquickjs::Result<()> {{ quickjs_callback_boundary(&ctx, {:?}, || {{ {setup} drop(host); let receiver = this.0.as_object().ok_or_else(|| rquickjs::Exception::throw_type(&ctx, \"incompatible attribute receiver\"))?; let target: rquickjs::Value = receiver.get({:?})?; quickjs_check_native_failure(&ctx)?; let target = target.as_object().ok_or_else(|| rquickjs::Exception::throw_type(&ctx, \"PutForwards target is not an object\"))?; let set = rquickjs::Function::from_value(quickjs_intrinsic(&ctx, \"Reflect.set\")?)?; let _: bool = set.call((target.clone(), {forward:?}, value))?; Ok(()) }}) }})",
            a.name, a.name
        )
    } else {
        format!("rquickjs::object::Accessor::new_get({get})")
    };
    let _ = writeln!(
        out,
        "    {target}.prop({:?}, {accessor}.enumerable().configurable())?;",
        a.name
    );
}

fn method_property(
    group: &OperationGroup,
    interface: Option<&str>,
    target: &str,
    out: &mut String,
) {
    let buffer_references = group.overloads.iter().any(Operation::buffer_references);
    let transfers_stored_values = interface == Some("EventTarget")
        && matches!(
            group.name.as_str(),
            "addEventListener" | "removeEventListener"
        );
    let stored_value_lease = buffer_references || transfers_stored_values;
    let this = if interface.is_some() {
        ", this: rquickjs::function::This<rquickjs::Value<'js>>"
    } else {
        ""
    };
    let _ = writeln!(
        out,
        "    {target}.prop({:?}, rquickjs::object::Property::from(rquickjs::Function::new(ctx.clone(), |ctx: rquickjs::Ctx<'js>{this}, args: rquickjs::function::Rest<rquickjs::Value<'js>>| -> rquickjs::Result<rquickjs::Value<'js>> {{ quickjs_callback_boundary(&ctx, {:?}, || {{",
        group.name, group.name
    );
    if let Some(name) = interface {
        let _ = writeln!(
            out,
            "        let host = quickjs_host::<T>(&ctx, &this.0, {name:?})?;"
        );
    }
    if buffer_references {
        out.push_str("        quickjs_begin_buffer_reference_lease(&ctx)?;\n");
    } else if stored_value_lease {
        out.push_str("        quickjs_begin_stored_value_lease(&ctx)?;\n");
    }
    if group.overloads.len() == 1 {
        operation(
            &group.overloads[0],
            interface.is_some(),
            transfers_stored_values,
            out,
        );
    } else {
        for (arity, index) in super::overload_dispatch(group) {
            let _ = writeln!(
                out,
                "        if matches!(args.0.len(), {arity}) {{ return (|| {{"
            );
            operation(
                &group.overloads[index],
                interface.is_some(),
                transfers_stored_values,
                out,
            );
            out.push_str("        })(); }\n");
        }
        out.push_str(
            "        Err(rquickjs::Exception::throw_type(&ctx, \"no matching overload\"))\n",
        );
    }
    out.push_str("    }) })?).writable().configurable().enumerable())?;\n");
}
fn operation(op: &Operation, instance: bool, transfers_stored_values: bool, out: &mut String) {
    let passes = arguments(&op.arguments, op.buffer_references(), out);
    // The host is behind an `Rc`, so the receiver is dereferenced: an
    // operation named `clone` would otherwise be `Rc::clone`.
    let receiver = if instance { "(*host)." } else { "T::" };
    let invocation = call(
        &format!("{receiver}{}({})", op.rust_name, passes.join(", ")),
        op.fast,
    );
    if matches!(op.return_type, Type::Undefined) {
        let transfer = if transfers_stored_values {
            "        quickjs_check_native_failure(&ctx)?;\n        quickjs_transfer_stored_value_lease(&ctx)?;\n"
        } else {
            ""
        };
        let _ = writeln!(
            out,
            "        {invocation};\n{transfer}        Ok(rquickjs::Value::new_undefined(ctx.clone()))"
        );
    } else {
        let conversion = operation_buffer_to_quickjs(&op.return_type, op.buffer_references())
            .unwrap_or_else(|| to_value(&op.return_type, "&ctx", "result"));
        let _ = writeln!(
            out,
            "        let result = {invocation};\n        {conversion}"
        );
    }
}
fn call(expr: &str, fast: FastApi) -> String {
    call_in(expr, fast, "&ctx")
}

fn call_in(expr: &str, fast: FastApi, ctx: &str) -> String {
    if fast.is_eligible() {
        expr.to_owned()
    } else {
        format!("{expr}.map_err(|e| throw_quickjs_error({ctx}, &e))?")
    }
}
fn operation_buffer_to_quickjs(ty: &Type, references: bool) -> Option<String> {
    if !references {
        return None;
    }
    Some(match ty {
        Type::Buffer(crate::model::BufferType::BufferSource) => {
            "buffer_source_ref_to_quickjs(&ctx, result)".into()
        }
        Type::Buffer(crate::model::BufferType::ArrayBufferView) => {
            "array_buffer_view_ref_to_quickjs(&ctx, result)".into()
        }
        _ => return None,
    })
}

fn arguments(args: &[Argument], references: bool, out: &mut String) -> Vec<String> {
    let min = args
        .iter()
        .take_while(|a| !a.optional && !a.variadic)
        .count();
    if min != 0 {
        let too_few = if min == 1 {
            "args.0.is_empty()".to_owned()
        } else {
            format!("args.0.len() < {min}")
        };
        let _ = writeln!(
            out,
            "        if {too_few} {{ return Err(rquickjs::Exception::throw_type(&ctx, \"missing required argument\")); }}"
        );
    }
    args.iter().enumerate().map(|(index,a)| {
        let name = &a.rust_name;
        let ty = super::rust_type::operation_buffer_type(&a.ty, references, Position::Owned);
        let reference_conversion = if references {
            match a.ty {
                Type::Buffer(crate::model::BufferType::BufferSource) =>
                    Some("buffer_source_ref_from_quickjs(&ctx, __raw_value)"),
                Type::Buffer(crate::model::BufferType::ArrayBufferView) =>
                    Some("array_buffer_view_ref_from_quickjs(&ctx, __raw_value)"),
                _ => None,
            }
        } else { None };
        let mut conversion = reference_conversion.map(str::to_owned).unwrap_or_else(||
            super::convert::legacy_null_to_empty(&a.ty, &a.attrs, "__raw_value", from_value(&a.ty, "&ctx", "__raw_value")));
        if let Some(suffix) = integer_suffix(&a.ty) {
            if a.clamp() { conversion = format!("rquickjs::Coerced::<f64>::from_js(&ctx, __raw_value).map(|v| clamp_{suffix}(v.0))"); }
            if a.enforce_range() { conversion = format!("rquickjs::Coerced::<f64>::from_js(&ctx, __raw_value).and_then(|v| enforce_{suffix}(v.0).map_err(|e| throw_quickjs_error(&ctx, &e)))"); }
        }
        if a.variadic {
            let source = if index == 0 {
                "args.0.iter()".to_owned()
            } else {
                format!("args.0.iter().skip({index})")
            };
            let _ = writeln!(out, "        let {name}: Vec<{ty}> = {source}.cloned().map(|__raw_value| {conversion}).collect::<rquickjs::Result<_>>()?;");
            return name.clone();
        }
        let raw = if index == 0 {
            "args.0.first()".to_owned()
        } else {
            format!("args.0.get({index})")
        };
        let _ = writeln!(out, "        let __raw_value = {raw}.cloned().unwrap_or_else(|| rquickjs::Value::new_undefined(ctx.clone()));");
        if a.optional {
            let _ = writeln!(out, "        let {name}: Option<{ty}> = if __raw_value.is_undefined() {{ None }} else {{ Some({conversion}?) }};");
            match &a.ty { t if is_string(t) => format!("{name}.as_deref()"), Type::Nullable(inner) if is_string(inner) => format!("{name}.as_ref().map(|v| v.as_deref())"), _ => name.clone() }
        } else { let _ = writeln!(out, "        let {name}: {ty} = {conversion}?;"); borrow_expr(&a.ty,name) }
    }).collect()
}
fn is_string(t: &Type) -> bool {
    matches!(t, Type::DomString | Type::UsvString | Type::ByteString)
}
fn borrow_expr(t: &Type, n: &str) -> String {
    match t {
        t if is_string(t) => format!("&{n}"),
        Type::Nullable(t) if is_string(t) => format!("{n}.as_deref()"),
        _ => n.into(),
    }
}

pub(super) fn from_value(ty: &Type, ctx: &str, value: &str) -> String {
    if let Some(suffix) = integer_suffix(ty) {
        return format!(
            "rquickjs::Coerced::<f64>::from_js({ctx}, {value}).map(|v| to_{suffix}(v.0))"
        );
    }
    match ty {
        Type::DomString | Type::UsvString => {
            format!(
                "rquickjs::Coerced::<rquickjs::String>::from_js({ctx}, {value}).and_then(|v| v.0.to_string_lossy())"
            )
        }
        Type::ByteString => format!("quickjs_bytestring({ctx}, {value})"),
        Type::Boolean => format!("rquickjs::Coerced::<bool>::from_js({ctx}, {value}).map(|v| v.0)"),
        Type::Float { unrestricted: true } => {
            format!("rquickjs::Coerced::<f64>::from_js({ctx}, {value}).map(|v| v.0 as f32)")
        }
        Type::Float {
            unrestricted: false,
        } => format!(
            "rquickjs::Coerced::<f64>::from_js({ctx}, {value}).and_then(|v| restricted_f32(v.0).map_err(|error| throw_quickjs_error({ctx}, &error)))"
        ),
        Type::Double { unrestricted } => {
            let rust = rust_type(ty, Position::Owned);
            format!(
                "rquickjs::Coerced::<f64>::from_js({ctx}, {value}).and_then(|v| {{ if {} || v.0.is_finite() {{ Ok(v.0 as {rust}) }} else {{ Err(rquickjs::Exception::throw_type({ctx}, \"non-finite number\")) }} }})",
                unrestricted
            )
        }
        Type::Buffer(kind) => format!(
            "quickjs_buffer_bytes({ctx}, {value}, {:?})",
            kind.idl_name()
        ),
        Type::CallbackInterface(name) => format!(
            "{{ let value = {value}; if value.is_object() {{ <{name} as rquickjs::FromJs>::from_js({ctx}, value) }} else {{ Err(rquickjs::Exception::throw_type({ctx}, \"the value is not an object, so it is not an `{name}`\")) }} }}"
        ),
        Type::Callback(name) => format!(
            "{{ let value = {value}; if value.is_function() {{ <{name} as rquickjs::FromJs>::from_js({ctx}, value) }} else {{ Err(rquickjs::Exception::throw_type({ctx}, \"the value is not callable, so it is not an `{name}`\")) }} }}"
        ),
        Type::Nullable(inner) => {
            let inner = from_value(inner, ctx, "value");
            format!(
                "{{ let value = {value}; if value.is_null() || value.is_undefined() {{ Ok(None) }} else {{ {inner}.map(Some) }} }}"
            )
        }
        Type::Sequence(inner) | Type::FrozenArray(inner) | Type::ObservableArray(inner) => {
            let inner = from_value(inner, ctx, "item");
            format!("quickjs_sequence({ctx}, {value}, |item| {inner})")
        }
        Type::Record(key, val) => {
            let key = from_value(key, ctx, "key");
            let val = from_value(val, ctx, "item");
            format!("quickjs_record({ctx}, {value}, |key| {key}, |item| {val})")
        }
        _ => format!(
            "<{} as rquickjs::FromJs>::from_js({ctx}, {value})",
            rust_type(ty, Position::Owned)
        ),
    }
}

/// Assignment to a nullable callback attribute is the one conversion site
/// where `[LegacyTreatNonObjectAsNull]` accepts any object, callable or not.
/// Other callback positions retain the strict gate in `from_value`.
fn from_value_for_attribute_setter(model: &Model, ty: &Type, ctx: &str, value: &str) -> String {
    if let Type::Nullable(inner) = ty
        && let Type::Callback(name) = inner.as_ref()
        && model
            .callback(name)
            .is_some_and(|callback| callback.attrs.has("LegacyTreatNonObjectAsNull"))
    {
        return format!(
            "{{ let value = {value}; if !value.is_object() {{ Ok(None) }} else {{ <{name} as rquickjs::FromJs>::from_js({ctx}, value).map(Some) }} }}"
        );
    }
    from_value(ty, ctx, value)
}

pub(super) fn to_value(ty: &Type, ctx: &str, value: &str) -> String {
    // Interface callbacks own `ctx`; generated union conversions receive
    // `&Ctx`. Clone the actual context in both positions without producing
    // `(&ctx).clone()`, which only adds a needless borrow in callbacks.
    let ctx_clone = if ctx == "&ctx" {
        "ctx.clone()"
    } else {
        "(*ctx).clone()"
    };
    match ty {
        Type::Undefined => {
            format!("{{ let _ = {value}; Ok(rquickjs::Value::new_undefined({ctx_clone})) }}")
        }
        Type::ByteString => format!(
            "rquickjs::IntoJs::into_js({value}.iter().map(|b| char::from(*b)).collect::<String>(), {ctx})"
        ),
        Type::Buffer(kind) => format!(
            "quickjs_buffer_value({ctx}, {value}, {:?})",
            kind.idl_name()
        ),
        Type::Nullable(inner) => {
            let inner = to_value(inner, ctx, "inner");
            format!(
                "match {value} {{ Some(inner) => {inner}, None => Ok(rquickjs::Value::new_null({ctx_clone})) }}"
            )
        }
        Type::Sequence(inner) | Type::ObservableArray(inner) => {
            let inner = to_value(inner, ctx, "item");
            format!("quickjs_sequence_value({ctx}, {value}, |item| {inner})")
        }
        Type::FrozenArray(inner) => {
            let inner = to_value(inner, ctx, "item");
            format!("quickjs_frozen_array_value({ctx}, {value}, |item| {inner})")
        }
        Type::Record(key, val) => {
            let key = to_value(key, ctx, "key");
            let val = to_value(val, ctx, "item");
            format!("quickjs_record_value({ctx}, {value}, |key| {key}, |item| {val})")
        }
        _ => format!("rquickjs::IntoJs::into_js({value}, {ctx})"),
    }
}

fn legacy_properties(model: &Model, interface: &Interface, out: &mut String) {
    use super::legacy::{LegacyProperties, SpecialOperation};
    let properties = LegacyProperties::resolve(model, interface);
    if properties.indexed_getter.is_none() && properties.named_getter.is_none() {
        return;
    }
    fn host(operation: SpecialOperation<'_>) -> String {
        format!(
            "let host = quickjs_host::<T>(ctx, object.as_value(), {:?})?;",
            operation.interface
        )
    }
    fn getter(operation: SpecialOperation<'_>) -> String {
        let setup = host(operation);
        let invocation = call_in(
            &format!(
                "<T as {}Ops>::{}(&*host, key)",
                operation.interface, operation.operation.rust_name
            ),
            operation.operation.fast,
            "ctx",
        );
        let value = to_value(&operation.operation.return_type, "ctx", "result");
        format!(
            "|ctx, object, key| quickjs_callback_boundary(ctx, {:?}, || {{ {setup} let result = {invocation}; {value} }})",
            operation.operation.name
        )
    }
    fn setter(operation: Option<SpecialOperation<'_>>) -> String {
        let Some(operation) = operation else {
            return "None".to_owned();
        };
        let setup = host(operation);
        let argument = &operation.operation.arguments[1];
        let conversion = super::convert::legacy_null_to_empty(
            &argument.ty,
            &argument.attrs,
            "value",
            from_value(&argument.ty, "ctx", "value"),
        );
        let pass = borrow_expr(&argument.ty, "value");
        let invocation = call_in(
            &format!(
                "<T as {}Ops>::{}(&*host, key, {pass})",
                operation.interface, operation.operation.rust_name
            ),
            operation.operation.fast,
            "ctx",
        );
        format!(
            "Some(|ctx, object, key, value| quickjs_callback_boundary(ctx, {:?}, || {{ {setup} let value = {conversion}?; {invocation}; Ok(()) }}))",
            operation.operation.name
        )
    }
    let indexed = properties.indexed_getter.map_or_else(|| "None".to_owned(), |operation| {
        let setup = host(operation);
        let declaring = operation.interface;
        let get = getter(operation);
        let set = setter(properties.indexed_setter);
        format!("Some(QuickJsIndexedProperties {{ indices: |ctx, object| quickjs_callback_boundary(ctx, {declaring:?}, || {{ {setup} <T as {declaring}Ops>::supported_property_indices(&*host).map_err(|e| throw_quickjs_error(ctx, &e)) }}), supports: |ctx, object, index| quickjs_callback_boundary(ctx, {declaring:?}, || {{ {setup} <T as {declaring}Ops>::is_supported_property_index(&*host, index).map_err(|e| throw_quickjs_error(ctx, &e)) }}), get: {get}, set: {set} }})")
    });
    let named = properties.named_getter.map_or_else(|| "None".to_owned(), |operation| {
        let setup = host(operation);
        let declaring = operation.interface;
        let get = getter(operation);
        let set = setter(properties.named_setter);
        let delete = properties.named_deleter.map_or_else(|| "None".to_owned(), |operation| {
            let setup = host(operation);
            let invocation = call_in(&format!("<T as {}Ops>::{}(&*host, key)", operation.interface, operation.operation.rust_name), operation.operation.fast, "ctx");
            let result = if operation.operation.return_type == Type::Boolean { format!("Ok({invocation})") } else { format!("{invocation}; Ok(true)") };
            format!("Some(|ctx, object, key| quickjs_callback_boundary(ctx, {:?}, || {{ {setup} {result} }}))", operation.operation.name)
        });
        format!("Some(QuickJsNamedProperties {{ names: |ctx, object| quickjs_callback_boundary(ctx, {declaring:?}, || {{ {setup} <T as {declaring}Ops>::supported_property_names(&*host).map_err(|e| throw_quickjs_error(ctx, &e)) }}), supports: |ctx, object, name| quickjs_callback_boundary(ctx, {declaring:?}, || {{ {setup} <T as {declaring}Ops>::is_supported_property_name(&*host, name).map_err(|e| throw_quickjs_error(ctx, &e)) }}), get: {get}, set: {set}, delete: {delete} }})")
    });
    let mut unforgeable = Vec::new();
    let mut is_global = false;
    for name in model.prototype_chain(&interface.name) {
        if let Some(ancestor) = model.interface(&name) {
            is_global |= ancestor.attrs.has("Global");
            for member in &ancestor.members {
                if let Member::Attribute(attribute) = member
                    && attribute.attrs.has("LegacyUnforgeable")
                {
                    unforgeable.push(format!("{:?}", attribute.name));
                }
            }
        }
    }
    let _ = writeln!(
        out,
        "    quickjs_cache_legacy(ctx, {:?}, QuickJsLegacyMethods {{ indexed: {indexed}, named: {named}, override_builtins: {}, unenumerable_names: {}, is_global: {is_global}, unforgeable_names: &[{}] }})?;",
        interface.name,
        properties.override_builtins,
        properties.unenumerable_names,
        unforgeable.join(", ")
    );
}
