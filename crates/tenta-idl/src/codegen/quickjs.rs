//! The QuickJS glue: an `rquickjs` class, prototype and constructor per
//! interface, and a namespace object per namespace.

use std::fmt::Write as _;

use crate::codegen::rust_type::{Position, float_literal, rust_type};
use crate::model::{
    Attribute, ConstValue, Constant, FastApi, Interface, Member, Model, Namespace, Operation,
    OperationGroup, Type,
};
use crate::naming;

const API_NOTE: &str = "\
/// `rquickjs` 0.12 items used by this file, each checked against
/// <https://docs.rs/rquickjs/0.12.2/rquickjs/>:
///
/// - `rquickjs::class::{JsClass, Trace, Tracer, Readable}` and
///   `rquickjs::JsLifetime`
/// - `rquickjs::Class::{define, prototype, instance}`
/// - `rquickjs::function::Constructor::new_class`
/// - `rquickjs::Object::{new, prop, set, set_prototype, into_value}`
/// - `rquickjs::object::{Accessor, Property}` through `Object::prop`
/// - `rquickjs::function::{Func, This, Opt, Rest}`
/// - `rquickjs::atom::PredefinedAtom::{SymbolToStringTag, SymbolIterator}` with
///   `rquickjs::Atom::from_predefined`
/// - `rquickjs::Exception::{throw_type, throw_range, throw_syntax}`
/// - `rquickjs::{FromJs, IntoJs}` for the argument and return conversions
";

/// Generates `<snake>_qjs.rs` for an interface.
pub fn interface_quickjs(model: &Model, interface: &Interface) -> String {
    let name = &interface.name;
    let snake = naming::snake_stem(name);
    let bound = trait_bound(model, interface);
    let class = format!("{name}Class");
    let mut out = String::new();
    let _ = write!(
        out,
        "// QuickJS bindings for the WebIDL interface `{name}`.\n\
         //\n\
         // Generated by `tenta-idl`; do not edit.\n"
    );

    let _ = write!(
        out,
        "\n/// The QuickJS class that carries a `{name}` host object.\n\
         ///\n\
         /// `T` is the host type that backs every `{name}` wrapper in the context.\n\
         ///\n\
         {API_NOTE}\
         pub struct {class}<T: {bound} + 'static>(pub T);\n\
         \n\
         impl<'js, T: {bound} + 'static> rquickjs::class::Trace<'js> for {class}<T> {{\n    \
         fn trace<'a>(&self, _tracer: rquickjs::class::Tracer<'a, 'js>) {{\n        \
         // The host object holds no QuickJS values; the wrapper world owns the\n        \
         // references that could form cycles.\n    }}\n}}\n\
         \n\
         // SAFETY: `{class}<T>` borrows no `'js` value, so re-branding the lifetime\n\
         // cannot make a value outlive its runtime.\n\
         unsafe impl<'js, T: {bound} + 'static> rquickjs::JsLifetime<'js> for {class}<T> {{\n    \
         type Changed<'to> = {class}<T>;\n}}\n"
    );

    let _ = write!(
        out,
        "\nimpl<'js, T: {bound} + 'static> rquickjs::class::JsClass<'js> for {class}<T> {{\n    \
         const NAME: &'static str = \"{name}\";\n    \
         type Mutable = rquickjs::class::Readable;\n\
         \n    \
         fn prototype(ctx: &rquickjs::Ctx<'js>) -> rquickjs::Result<Option<rquickjs::Object<'js>>> {{\n        \
         let prototype = rquickjs::Object::new(ctx.clone())?;\n        \
         install_{snake}_prototype::<T>(ctx, &prototype)?;\n        \
         Ok(Some(prototype))\n    }}\n\
         \n    \
         fn constructor(\n        ctx: &rquickjs::Ctx<'js>,\n    ) -> rquickjs::Result<Option<rquickjs::function::Constructor<'js>>> {{\n"
    );
    if interface.constructors.is_empty() {
        let _ = write!(
            out,
            "        // `{name}` declares no `constructor`, so calling it throws.\n        \
             let constructor = rquickjs::function::Constructor::new_class::<Self, _, _>(\n            \
             ctx.clone(),\n            |ctx: rquickjs::Ctx<'js>| -> rquickjs::Result<rquickjs::Value<'js>> {{\n                \
             Err(rquickjs::Exception::throw_type(&ctx, \"Illegal constructor\"))\n            }},\n        )?;\n        \
             Ok(Some(constructor))\n    }}\n}}\n"
        );
    } else {
        let constructor = &interface.constructors[0];
        let parameters = constructor
            .arguments
            .iter()
            .map(|argument| {
                let ty = rust_type(&argument.ty, Position::Owned);
                if argument.variadic {
                    format!("{}: rquickjs::function::Rest<{ty}>", argument.rust_name)
                } else if argument.optional {
                    format!("{}: rquickjs::function::Opt<{ty}>", argument.rust_name)
                } else {
                    format!("{}: {ty}", argument.rust_name)
                }
            })
            .collect::<Vec<_>>();
        let passes = constructor
            .arguments
            .iter()
            .map(quickjs_pass)
            .collect::<Vec<_>>();
        let mut signature = vec!["ctx: rquickjs::Ctx<'js>".to_string()];
        signature.extend(parameters);
        // Thread the realm (host context) in as the constructor's first argument,
        // mirroring the V8 path.
        let call_args = if passes.is_empty() {
            "&realm".to_owned()
        } else {
            format!("&realm, {}", passes.join(", "))
        };
        let _ = write!(
            out,
            "        let constructor = rquickjs::function::Constructor::new_class::<Self, _, _>(\n            \
             ctx.clone(),\n            \
             |{}| -> rquickjs::Result<rquickjs::Value<'js>> {{\n                \
             let realm = world_realm_quickjs(&ctx)?;\n                \
             let host = T::{}({}).map_err(|error| throw_quickjs_error(&ctx, &error))?;\n                \
             let instance = rquickjs::Class::instance(ctx.clone(), {class}(host))?;\n                \
             Ok(instance.into_value())\n            }},\n        )?;\n        \
             Ok(Some(constructor))\n    }}\n}}\n",
            signature.join(", "),
            constructor.rust_name,
            call_args,
        );
    }

    prototype_installer(model, interface, &bound, &class, &mut out);

    let _ = write!(
        out,
        "\n/// Installs `{name}` on `global` and registers it with `registry`.\n\
         pub fn install_{snake}<'js, T: {bound} + 'static>(\n    \
         ctx: &rquickjs::Ctx<'js>,\n    \
         global: &rquickjs::Object<'js>,\n    \
         registry: &mut dyn InterfaceRegistry,\n\
         ) -> rquickjs::Result<()> {{\n    \
         let _ = ctx;\n    \
         rquickjs::Class::<{class}<T>>::define(global)?;\n    \
         register_{snake}(registry);\n    Ok(())\n}}\n"
    );
    out
}

/// Generates `<snake>_qjs.rs` for a namespace.
pub fn namespace_quickjs(_model: &Model, namespace: &Namespace) -> String {
    let name = &namespace.name;
    let snake = naming::snake_stem(name);
    let bound = format!("{name}Ops");
    let mut out = String::new();
    let _ = write!(
        out,
        "// QuickJS bindings for the WebIDL namespace `{name}`.\n\
         //\n\
         // Generated by `tenta-idl`; do not edit.\n"
    );
    let _ = write!(
        out,
        "\n/// Installs the `{name}` namespace object on `global` and registers it.\n\
         ///\n\
         {API_NOTE}\
         pub fn install_{snake}<'js, T: {bound} + 'static>(\n    \
         ctx: &rquickjs::Ctx<'js>,\n    \
         global: &rquickjs::Object<'js>,\n    \
         registry: &mut dyn InterfaceRegistry,\n\
         ) -> rquickjs::Result<()> {{\n    \
         let namespace = rquickjs::Object::new(ctx.clone())?;\n"
    );
    for constant in &namespace.constants {
        constant_property(constant, "namespace", &mut out);
    }
    for member in &namespace.members {
        match member {
            Member::Attribute(attribute) => {
                static_accessor_property(attribute, "namespace", &mut out);
            }
            Member::Operation(group) => {
                static_method_property(group, "namespace", &mut out);
            }
        }
    }
    let _ = write!(
        out,
        "    namespace.prop(\n        \
         rquickjs::Atom::from_predefined(ctx.clone(), rquickjs::atom::PredefinedAtom::SymbolToStringTag),\n        \
         rquickjs::object::Property::from(\"{name}\").configurable(),\n    )?;\n    \
         global.set(\"{name}\", namespace)?;\n    \
         register_{snake}(registry);\n    Ok(())\n}}\n"
    );
    out
}

fn trait_bound(model: &Model, interface: &Interface) -> String {
    let mut bounds = vec![format!("{}Ops", interface.name)];
    let mut parent = interface.parent.clone();
    while let Some(name) = parent {
        let Some(ancestor) = model.interface(&name) else {
            break;
        };
        bounds.push(format!("{name}Ops"));
        parent = ancestor.parent.clone();
    }
    if !interface.constructors.is_empty() {
        bounds.push(format!("{}Constructor", interface.name));
    }
    bounds.join(" + ")
}

fn prototype_installer(
    model: &Model,
    interface: &Interface,
    bound: &str,
    class: &str,
    out: &mut String,
) {
    let name = &interface.name;
    let snake = naming::snake_stem(name);
    let _ = write!(
        out,
        "\n/// Fills the `{name}` prototype: constants, accessors, methods,\n\
         /// `Symbol.toStringTag` and the link to the parent prototype.\n\
         fn install_{snake}_prototype<'js, T: {bound} + 'static>(\n    \
         ctx: &rquickjs::Ctx<'js>,\n    \
         prototype: &rquickjs::Object<'js>,\n\
         ) -> rquickjs::Result<()> {{\n"
    );
    for constant in &interface.constants {
        constant_property(constant, "prototype", out);
    }
    for member in &interface.members {
        match member {
            Member::Attribute(attribute) if attribute.is_static => {
                static_accessor_property(attribute, "prototype", out);
            }
            Member::Attribute(attribute) => {
                accessor_property(attribute, class, out);
            }
            Member::Operation(group) if group.is_static => {
                static_method_property(group, "prototype", out);
            }
            Member::Operation(group) => {
                method_property(group, class, out);
            }
        }
    }
    if let Some(iterable) = &interface.iterable
        && iterable.key.is_none()
        && !iterable.is_async
    {
        out.push_str(
            "    {\n        // A WebIDL value iterator exposes `%Array.prototype.values%`.\n        let array: rquickjs::Object = ctx.globals().get(\"Array\")?;\n        let array_prototype: rquickjs::Object = array.get(\"prototype\")?;\n        let values: rquickjs::Function = array_prototype.get(\"values\")?;\n        prototype.set(\n            rquickjs::Atom::from_predefined(ctx.clone(), rquickjs::atom::PredefinedAtom::SymbolIterator),\n            values,\n        )?;\n    }\n",
        );
    }
    if let Some(parent) = &interface.parent
        && model.interface(parent).is_some()
    {
        let _ = write!(
            out,
            "    if let Some(parent) = rquickjs::Class::<{parent}Class<T>>::prototype(ctx)? {{\n        \
             prototype.set_prototype(Some(&parent))?;\n    }}\n"
        );
    }
    let _ = write!(
        out,
        "    prototype.prop(\n        \
         rquickjs::Atom::from_predefined(ctx.clone(), rquickjs::atom::PredefinedAtom::SymbolToStringTag),\n        \
         rquickjs::object::Property::from(\"{name}\").configurable(),\n    )?;\n    Ok(())\n}}\n"
    );
}

fn constant_property(constant: &Constant, target: &str, out: &mut String) {
    let value = match &constant.value {
        ConstValue::Boolean(value) => value.to_string(),
        ConstValue::Integer(value) => format!("{value}i64"),
        ConstValue::Float(value) => float_literal(*value),
        ConstValue::Null => "rquickjs::Null".to_string(),
    };
    let _ = writeln!(
        out,
        "    {target}.prop(\"{}\", rquickjs::object::Property::from({value}).enumerable())?;",
        constant.name
    );
}

fn accessor_property(attribute: &Attribute, class: &str, out: &mut String) {
    let name = &attribute.name;
    let getter_type = rust_type(&attribute.ty, Position::Owned);
    let getter_body = match attribute.fast_getter {
        FastApi::Eligible => format!("Ok(this.0.borrow().0.{}())", attribute.getter_name),
        FastApi::Ineligible(_) => format!(
            "this.0.borrow().0.{}().map_err(|error| throw_quickjs_error(&ctx, &error))",
            attribute.getter_name
        ),
    };
    // A fast-eligible getter cannot fail, so its closure never touches `ctx`.
    let getter_ctx = if attribute.fast_getter.is_eligible() {
        "_ctx"
    } else {
        "ctx"
    };
    let getter = format!(
        "|{getter_ctx}: rquickjs::Ctx<'js>, this: rquickjs::function::This<rquickjs::Class<'js, {class}<T>>>| -> rquickjs::Result<{getter_type}> {{ {getter_body} }}"
    );
    match (&attribute.setter_name, attribute.fast_setter) {
        (Some(setter_name), Some(fast)) => {
            let value_type = rust_type(&attribute.ty, Position::Owned);
            let pass = borrow_expr(&attribute.ty, "value");
            let setter_body = match fast {
                FastApi::Eligible => {
                    format!("this.0.borrow().0.{setter_name}({pass});\n            Ok(())")
                }
                FastApi::Ineligible(_) => format!(
                    "this.0\n                .borrow()\n                .0\n                .{setter_name}({pass})\n                .map_err(|error| throw_quickjs_error(&ctx, &error))"
                ),
            };
            let setter_ctx = if fast.is_eligible() { "_ctx" } else { "ctx" };
            let _ = write!(
                out,
                "    prototype.prop(\n        \"{name}\",\n        rquickjs::object::Accessor::new(\n            {getter},\n            |{setter_ctx}: rquickjs::Ctx<'js>, this: rquickjs::function::This<rquickjs::Class<'js, {class}<T>>>, value: {value_type}| -> rquickjs::Result<()> {{\n            {setter_body}\n            }},\n        )\n        .enumerable()\n        .configurable(),\n    )?;\n"
            );
        }
        _ => {
            let _ = write!(
                out,
                "    prototype.prop(\n        \"{name}\",\n        rquickjs::object::Accessor::new_get({getter})\n            .enumerable()\n            .configurable(),\n    )?;\n"
            );
        }
    }
}

fn static_accessor_property(attribute: &Attribute, target: &str, out: &mut String) {
    let name = &attribute.name;
    let getter_type = rust_type(&attribute.ty, Position::Owned);
    let _ = write!(
        out,
        "    {target}.prop(\n        \"{name}\",\n        rquickjs::object::Accessor::new_get(\n            |ctx: rquickjs::Ctx<'js>| -> rquickjs::Result<{getter_type}> {{\n                T::{}().map_err(|error| throw_quickjs_error(&ctx, &error))\n            }},\n        )\n        .enumerable()\n        .configurable(),\n    )?;\n",
        attribute.getter_name
    );
}

fn method_property(group: &OperationGroup, class: &str, out: &mut String) {
    let name = &group.name;
    if group.overloads.len() == 1 {
        let closure = method_closure(&group.overloads[0], Some(class));
        let _ = write!(
            out,
            "    prototype.prop(\n        \"{name}\",\n        rquickjs::object::Property::from(rquickjs::function::Func::new({closure}))\n            .writable()\n            .configurable()\n            .enumerable(),\n    )?;\n"
        );
        return;
    }
    // Overloads take the raw argument list and dispatch on its length.
    let mut arms = String::new();
    for overload in &group.overloads {
        let count = overload.arguments.len();
        let mut bindings = String::new();
        let mut passes = Vec::new();
        for (index, argument) in overload.arguments.iter().enumerate() {
            let ty = rust_type(&argument.ty, Position::Owned);
            let source = format!("args.0.get({index}).cloned()");
            if argument.optional {
                let _ = write!(
                    bindings,
                    "                let {0}: Option<{ty}> = match {source} {{\n                    Some(value) => Some(rquickjs::FromJs::from_js(&ctx, value)?),\n                    None => None,\n                }};\n",
                    argument.rust_name
                );
                passes.push(borrow_optional_expr(&argument.ty, &argument.rust_name));
            } else {
                let _ = write!(
                    bindings,
                    "                let {0}: {ty} = match {source} {{\n                    Some(value) => rquickjs::FromJs::from_js(&ctx, value)?,\n                    None => return Err(rquickjs::Exception::throw_type(&ctx, \"missing argument\")),\n                }};\n",
                    argument.rust_name
                );
                passes.push(borrow_expr(&argument.ty, &argument.rust_name));
            }
        }
        let call = call_expression(overload, "this.0.borrow().0.", &passes);
        let _ = write!(
            arms,
            "            {count} => {{\n{bindings}                {call}\n            }}\n"
        );
    }
    let _ = write!(
        out,
        "    prototype.prop(\n        \"{name}\",\n        rquickjs::object::Property::from(rquickjs::function::Func::new(\n            |ctx: rquickjs::Ctx<'js>, this: rquickjs::function::This<rquickjs::Class<'js, {class}<T>>>, args: rquickjs::function::Rest<rquickjs::Value<'js>>| -> rquickjs::Result<rquickjs::Value<'js>> {{\n            match args.0.len() {{\n{arms}            _ => Err(rquickjs::Exception::throw_type(\n                    &ctx,\n                    \"no overload of '{name}' matches the argument count\",\n                )),\n            }}\n            }},\n        ))\n        .writable()\n        .configurable()\n        .enumerable(),\n    )?;\n"
    );
}

fn static_method_property(group: &OperationGroup, target: &str, out: &mut String) {
    let name = &group.name;
    let closure = method_closure(&group.overloads[0], None);
    let _ = write!(
        out,
        "    {target}.prop(\n        \"{name}\",\n        rquickjs::object::Property::from(rquickjs::function::Func::new({closure}))\n            .writable()\n            .configurable()\n            .enumerable(),\n    )?;\n"
    );
}

/// Builds the closure for an operation with a single overload.
fn method_closure(operation: &Operation, class: Option<&str>) -> String {
    // A fast-eligible operation cannot fail, so its closure never uses `ctx`.
    let ctx = if operation.fast.is_eligible() {
        "_ctx"
    } else {
        "ctx"
    };
    let mut signature = vec![format!("{ctx}: rquickjs::Ctx<'js>")];
    if let Some(class) = class {
        signature.push(format!(
            "this: rquickjs::function::This<rquickjs::Class<'js, {class}<T>>>"
        ));
    }
    let mut passes = Vec::new();
    for argument in &operation.arguments {
        let ty = rust_type(&argument.ty, Position::Owned);
        if argument.variadic {
            signature.push(format!(
                "{}: rquickjs::function::Rest<{ty}>",
                argument.rust_name
            ));
        } else if argument.optional {
            signature.push(format!(
                "{}: rquickjs::function::Opt<{ty}>",
                argument.rust_name
            ));
        } else {
            signature.push(format!("{}: {ty}", argument.rust_name));
        }
        passes.push(quickjs_pass(argument));
    }
    let receiver = if class.is_some() {
        "this.0.borrow().0."
    } else {
        "T::"
    };
    let return_type = quickjs_return_type(operation);
    let body = call_expression(operation, receiver, &passes);
    format!(
        "|{}| -> rquickjs::Result<{return_type}> {{ {body} }}",
        signature.join(", ")
    )
}

fn quickjs_return_type(operation: &Operation) -> String {
    match operation.return_type {
        Type::Undefined => "()".to_string(),
        _ => rust_type(&operation.return_type, Position::Owned),
    }
}

fn call_expression(operation: &Operation, receiver: &str, passes: &[String]) -> String {
    let call = format!("{receiver}{}({})", operation.rust_name, passes.join(", "));
    match operation.fast {
        FastApi::Eligible if operation.return_type == Type::Undefined => {
            format!("{call};\n                Ok(())")
        }
        FastApi::Eligible => format!("Ok({call})"),
        FastApi::Ineligible(_) => {
            format!("{call}.map_err(|error| throw_quickjs_error(&ctx, &error))")
        }
    }
}

/// The expression that turns an `rquickjs` binding into the trait argument.
fn quickjs_pass(argument: &crate::model::Argument) -> String {
    let name = &argument.rust_name;
    if argument.variadic {
        return format!("{name}.0");
    }
    if argument.optional {
        return match &argument.ty {
            ty if is_string(ty) => format!("{name}.0.as_deref()"),
            // See `pass_expr` in `v8.rs`: the outer `Option` has to be borrowed by
            // reference, or the closure returns a `&str` borrowed from its own
            // parameter. This arm is not compiled by any gate in this repository
            // (the `quickjs` feature does not build), so the V8 comment is where
            // the reasoning lives and this is its mechanical counterpart.
            Type::Nullable(inner) if is_string(inner) => {
                format!("{name}.0.as_ref().map(|inner| inner.as_deref())")
            }
            _ => format!("{name}.0"),
        };
    }
    borrow_expr(&argument.ty, name)
}

fn borrow_expr(ty: &Type, name: &str) -> String {
    match ty {
        ty if is_string(ty) => format!("&{name}"),
        Type::Nullable(inner) if is_string(inner) => format!("{name}.as_deref()"),
        _ => name.to_string(),
    }
}

fn borrow_optional_expr(ty: &Type, name: &str) -> String {
    match ty {
        ty if is_string(ty) => format!("{name}.as_deref()"),
        Type::Nullable(inner) if is_string(inner) => {
            format!("{name}.map(|inner| inner.as_deref())")
        }
        _ => name.to_string(),
    }
}

fn is_string(ty: &Type) -> bool {
    matches!(ty, Type::DomString | Type::UsvString | Type::ByteString)
}
