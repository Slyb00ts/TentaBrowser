const API_NOTE: &str = "\
/// rusty_v8 152.x items used by this file, each checked against
/// <https://docs.rs/v8/152.2.0/v8/>:
///
/// - `v8::FunctionTemplate::builder`, `v8::FunctionTemplate::new`,
///   `FunctionBuilder::{signature, length, build, build_fast}`
/// - `FunctionTemplate::{set_class_name, inherit, prototype_template,
///   instance_template, set_accessor_property}`
/// - `ObjectTemplate::{new, set_internal_field_count, set_accessor_property,
///   set_indexed_property_handler, set_named_property_handler}`
/// - `Template::{set, set_with_attr, set_intrinsic_data_property}` with
///   `v8::String::new`
/// - `v8::Signature::new` for the WebIDL brand check
/// - `v8::FunctionCallbackArguments::{this, get, length, is_construct_call}`
/// - `v8::ReturnValue::{set, set_bool, set_int32, set_uint32, set_double,
///   set_null, set_undefined}`
/// - `v8::fast_api::{CFunction, CFunctionInfo, CTypeInfo, Flags,
///   Int64Representation, Type, FastApiOneByteString}`
/// - `v8::Local<v8::Object>::{get_aligned_pointer_from_internal_field,
///   set_aligned_pointer_in_internal_field, get, set, create_data_property,
///   internal_field_count}` (through the prelude helpers)
/// - `v8::Global`, `v8::Local::new`
/// - `v8::PropertyAttribute::{NONE, READ_ONLY, DONT_ENUM, DONT_DELETE}`
/// - `v8::Symbol::{get_to_string_tag, get_iterator, get_unscopables}`,
///   `v8::Intrinsic::ArrayProtoValues`
/// - `v8::Value::{to_uint32, int32_value, number_value, boolean_value,
///   to_rust_string_lossy, is_null_or_undefined}` (through the prelude)
/// - `v8::Exception::{type_error, range_error, syntax_error}` and
///   `PinScope::throw_exception` (through the prelude)
";

/// Generates `<snake>_v8.rs` for an interface.
pub fn interface_v8(model: &Model, interface: &Interface) -> String {
    let name = &interface.name;
    let snake = naming::snake_stem(name);
    let bound = trait_bound(model, interface);
    let mut out = String::new();
    let _ = write!(
        out,
        "// V8 bindings for the WebIDL interface `{name}`.\n\
         //\n\
         // Generated by `tenta-idl`; do not edit.\n"
    );

    install_function(model, interface, &bound, &mut out);
    constructor_callback(interface, &bound, &mut out);

    for member in &interface.members {
        match member {
            Member::Attribute(attribute) => {
                attribute_callbacks(interface, attribute, &bound, &mut out);
            }
            Member::Operation(group) => {
                operation_callbacks(&interface.name, group, &bound, &mut out);
            }
        }
    }
    if let Some(operation) = interface.indexed_getter.as_ref().and_then(|getter| {
        interface
            .members
            .iter()
            .find_map(|m| match m {
                Member::Operation(group) if &group.name == getter => group.overloads.first(),
                _ => None,
            })
            .or_else(|| interface.special_operations.first())
    }) {
        indexed_getter_callback(&interface.name, operation, &bound, &mut out);
    }
    let _ = snake;
    out
}

/// Generates `<snake>_v8.rs` for a namespace.
pub fn namespace_v8(_model: &Model, namespace: &Namespace) -> String {
    let name = &namespace.name;
    let snake = naming::snake_stem(name);
    let bound = format!("{name}Ops");
    let mut out = String::new();
    let _ = write!(
        out,
        "// V8 bindings for the WebIDL namespace `{name}`.\n\
         //\n\
         // Generated by `tenta-idl`; do not edit.\n"
    );
    let _ = write!(
        out,
        "\n/// Installs the `{name}` namespace object on `global_template` and\n\
         /// registers it with `registry`.\n\
         ///\n\
         {API_NOTE}\
         pub fn install_{snake}<T: {bound} + 'static>(\n    \
         scope: &mut v8::PinScope<'_, '_>,\n    \
         global_template: v8::Local<'_, v8::ObjectTemplate>,\n    \
         registry: &mut dyn InterfaceRegistry,\n\
         ) -> Result<(), JsError> {{\n    \
         let namespace = v8::ObjectTemplate::new(scope);\n"
    );
    for constant in &namespace.constants {
        constant_install(constant, "namespace", None, &mut out);
    }
    for member in &namespace.members {
        match member {
            Member::Attribute(attribute) => {
                accessor_install(name, attribute, "namespace", None, &mut out);
            }
            Member::Operation(group) => {
                method_install(name, group, "namespace", None, &mut out);
            }
        }
    }
    let _ = write!(
        out,
        "    {{\n        \
         let key = v8::Symbol::get_to_string_tag(scope);\n        \
         let value = v8_string(scope, \"{name}\")?;\n        \
         namespace.set_with_attr(key.into(), value.into(), to_string_tag_attributes());\n    \
         }}\n    \
         {{\n        \
         let key = v8_string(scope, \"{name}\")?;\n        \
         global_template.set_with_attr(\n            \
         key.into(),\n            namespace.into(),\n            v8::PropertyAttribute::DONT_ENUM,\n        );\n    \
         }}\n    \
         register_{snake}(registry);\n    Ok(())\n}}\n"
    );
    for member in &namespace.members {
        match member {
            Member::Attribute(attribute) => {
                attribute_callbacks_static(name, attribute, &bound, &mut out);
            }
            Member::Operation(group) => {
                operation_callbacks(name, group, &bound, &mut out);
            }
        }
    }
    out
}

fn trait_bound(model: &Model, interface: &Interface) -> String {
    let mut bounds = vec![format!("{}Ops", interface.name)];
    // An interface's install re-installs its ancestors' `[LegacyUnforgeable]`
    // members on its own instance template (see `install_function`); those
    // getters are generic over the ancestor's `Constructor` bound, so the host
    // type must satisfy every ancestor constructor too, not just its own.
    let mut constructors = Vec::new();
    if !interface.constructors.is_empty() {
        constructors.push(format!("{}Constructor", interface.name));
    }
    let mut parent = interface.parent.clone();
    while let Some(name) = parent {
        let Some(ancestor) = model.interface(&name) else {
            break;
        };
        bounds.push(format!("{name}Ops"));
        if !ancestor.constructors.is_empty() {
            constructors.push(format!("{name}Constructor"));
        }
        parent = ancestor.parent.clone();
    }
    bounds.extend(constructors);
    bounds.join(" + ")
}

fn install_function(model: &Model, interface: &Interface, bound: &str, out: &mut String) {
    let name = &interface.name;
    let snake = naming::snake_stem(name);
    let chain = model.prototype_chain(name).join(" -> ");
    let _ = write!(
        out,
        "\n/// Installs `{name}` on `global_template` and registers it with `registry`.\n\
         ///\n\
         /// Prototype chain: `{chain}`. The parent interface must be installed\n\
         /// first: this function reads it from the isolate's `TemplateCache`.\n\
         ///\n\
         /// `T` is the host type that backs every `{name}` wrapper in the context.\n\
         ///\n\
         {API_NOTE}\
         pub fn install_{snake}<T: {bound} + 'static>(\n    \
         scope: &mut v8::PinScope<'_, '_>,\n    \
         global_template: v8::Local<'_, v8::ObjectTemplate>,\n    \
         registry: &mut dyn InterfaceRegistry,\n\
         ) -> Result<v8::Global<v8::FunctionTemplate>, JsError> {{\n    \
         let constructor = v8::FunctionTemplate::builder(construct_{snake}::<T>).build(scope);\n    \
         let class_name = v8_string(scope, \"{name}\")?;\n    \
         constructor.set_class_name(class_name);\n"
    );
    if let Some(parent) = &interface.parent {
        let _ = write!(
            out,
            "    let parent = cached_template(scope, \"{parent}\").ok_or_else(|| {{\n        \
             JsError::type_error(\"{name}: the parent interface {parent} is not installed\")\n    \
             }})?;\n    constructor.inherit(parent);\n"
        );
    }
    let _ = write!(
        out,
        "    let signature = v8::Signature::new(scope, constructor);\n    \
         let prototype = constructor.prototype_template(scope);\n    \
         let instance = constructor.instance_template(scope);\n    \
         instance.set_internal_field_count(1);\n"
    );

    for constant in &interface.constants {
        constant_install(constant, "constructor", Some("prototype"), out);
    }

    let mut unscopables: Vec<String> = Vec::new();
    for member in &interface.members {
        match member {
            Member::Attribute(attribute) => {
                let target = if attribute.is_static {
                    "constructor"
                } else if attribute.legacy_unforgeable() {
                    "instance"
                } else {
                    "prototype"
                };
                accessor_install(name, attribute, target, Some("signature"), out);
                if attribute.unscopable() {
                    unscopables.push(attribute.name.clone());
                }
            }
            Member::Operation(group) => {
                let target = if group.is_static {
                    "constructor"
                } else {
                    "prototype"
                };
                method_install(name, group, target, Some("signature"), out);
                if group.unscopable() {
                    unscopables.push(group.name.clone());
                }
            }
        }
    }

    // `[LegacyUnforgeable]` members are own, non-configurable accessors on each
    // instance. V8 does not inherit instance-template accessors through the
    // prototype chain (unlike prototype methods), so a derived interface must
    // re-install every ancestor's unforgeable members on its own instance
    // template — otherwise e.g. `isTrusted` is present on `Event` but missing on
    // `MouseEvent`. The derived signature keeps each getter bound to instances
    // of this interface.
    let mut ancestor = interface.parent.clone();
    while let Some(ancestor_name) = ancestor {
        let Some(ancestor_interface) = model.interface(&ancestor_name) else {
            break;
        };
        for member in &ancestor_interface.members {
            if let Member::Attribute(attribute) = member
                && !attribute.is_static
                && attribute.legacy_unforgeable()
            {
                accessor_install(
                    &ancestor_interface.name,
                    attribute,
                    "instance",
                    Some("signature"),
                    out,
                );
            }
        }
        ancestor = ancestor_interface.parent.clone();
    }

    if !unscopables.is_empty() {
        out.push_str(
            "    {\n        // `[Unscopable]` members are listed on `@@unscopables`.\n        let unscopables = v8::ObjectTemplate::new(scope);\n",
        );
        for member in &unscopables {
            let _ = write!(
                out,
                "        {{\n            let key = v8_string(scope, \"{member}\")?;\n            let value = v8::Boolean::new(scope, true);\n            unscopables.set(key.into(), value.into());\n        }}\n"
            );
        }
        out.push_str(
            "        let key = v8::Symbol::get_unscopables(scope);\n        prototype.set_with_attr(key.into(), unscopables.into(), v8::PropertyAttribute::DONT_ENUM);\n    }\n",
        );
    }

    if interface.indexed_getter.is_some() {
        let _ = write!(
            out,
            "    instance.set_indexed_property_handler(\n        \
             v8::IndexedPropertyHandlerConfiguration::new().getter(indexed_get_{snake}::<T>),\n    );\n"
        );
    }

    if let Some(iterable) = &interface.iterable
        && iterable.key.is_none()
        && !iterable.is_async
    {
        out.push_str(
            "    {\n        // A WebIDL value iterator exposes `%Array.prototype.values%`.\n        let key = v8::Symbol::get_iterator(scope);\n        prototype.set_intrinsic_data_property(\n            key.into(),\n            v8::Intrinsic::ArrayProtoValues,\n            v8::PropertyAttribute::DONT_ENUM,\n        );\n    }\n",
        );
    }

    let _ = write!(
        out,
        "    {{\n        \
         let key = v8::Symbol::get_to_string_tag(scope);\n        \
         prototype.set_with_attr(key.into(), class_name.into(), to_string_tag_attributes());\n    \
         }}\n    \
         global_template.set_with_attr(\n        \
         class_name.into(),\n        constructor.into(),\n        v8::PropertyAttribute::DONT_ENUM,\n    );\n    \
         cache_template(scope, \"{name}\", constructor);\n    \
         register_{snake}(registry);\n    \
         Ok(v8::Global::new(scope.as_ref(), constructor))\n}}\n"
    );
}

fn constant_install(constant: &Constant, primary: &str, secondary: Option<&str>, out: &mut String) {
    let value = match &constant.value {
        ConstValue::Boolean(value) => format!("v8::Boolean::new(scope, {value})"),
        ConstValue::Integer(value) => {
            if matches!(
                constant.ty,
                Type::Octet | Type::UnsignedShort | Type::UnsignedLong | Type::UnsignedLongLong
            ) {
                format!("v8::Integer::new_from_unsigned(scope, {value}u32)")
            } else {
                format!("v8::Integer::new(scope, {value}i32)")
            }
        }
        ConstValue::Float(value) => {
            format!("v8::Number::new(scope, {})", float_literal(*value))
        }
        ConstValue::Null => "v8::null(scope)".to_string(),
    };
    let _ = write!(
        out,
        "    {{\n        let key = v8_string(scope, \"{}\")?;\n        let value = {value};\n        {primary}.set_with_attr(key.into(), value.into(), constant_attributes());\n",
        constant.name
    );
    if let Some(secondary) = secondary {
        let _ = writeln!(
            out,
            "        {secondary}.set_with_attr(key.into(), value.into(), constant_attributes());"
        );
    }
    out.push_str("    }\n");
}

fn accessor_install(
    interface: &str,
    attribute: &Attribute,
    target: &str,
    signature: Option<&str>,
    out: &mut String,
) {
    let snake = naming::snake_stem(interface);
    let member = naming::snake_stem(&attribute.name);
    let signature_call = match signature {
        Some(name) if !attribute.is_static => format!("\n            .signature({name})"),
        _ => String::new(),
    };
    let getter_build = match attribute.fast_getter {
        FastApi::Eligible => format!(
            ".build_fast(scope, &{}Getter::<T>::TABLE)",
            fast_struct(interface, &attribute.name)
        ),
        FastApi::Ineligible(_) => ".build(scope)".to_string(),
    };
    let _ = write!(
        out,
        "    {{\n        \
         let key = v8_string(scope, \"{}\")?;\n        \
         let getter = v8::FunctionTemplate::builder(get_{snake}_{member}::<T>){signature_call}\n            .length(0)\n            {getter_build};\n",
        attribute.name
    );
    let setter = if attribute.readonly
        && attribute.put_forwards().is_none()
        && !attribute.replaceable()
    {
        "None".to_string()
    } else {
        let setter_build = match attribute.fast_setter {
            Some(FastApi::Eligible) => format!(
                ".build_fast(scope, &{}Setter::<T>::TABLE)",
                fast_struct(interface, &attribute.name)
            ),
            _ => ".build(scope)".to_string(),
        };
        let _ = write!(
            out,
            "        let setter = v8::FunctionTemplate::builder(set_{snake}_{member}::<T>){signature_call}\n            .length(1)\n            {setter_build};\n"
        );
        "Some(setter)".to_string()
    };
    let attributes = if attribute.legacy_unforgeable() {
        "unforgeable_attributes()"
    } else {
        "v8::PropertyAttribute::NONE"
    };
    let _ = write!(
        out,
        "        {target}.set_accessor_property(key.into(), Some(getter), {setter}, {attributes});\n    }}\n"
    );
}

fn method_install(
    interface: &str,
    group: &OperationGroup,
    target: &str,
    signature: Option<&str>,
    out: &mut String,
) {
    let snake = naming::snake_stem(interface);
    let member = naming::snake_stem(&group.name);
    let signature_call = match signature {
        Some(name) if !group.is_static => format!("\n            .signature({name})"),
        _ => String::new(),
    };
    let length = group
        .overloads
        .iter()
        .map(|o| o.required_argument_count())
        .min()
        .unwrap_or(0);
    let build = match group.fast {
        FastApi::Eligible => format!(
            ".build_fast(scope, &{}Method::<T>::TABLE)",
            fast_struct(interface, &group.name)
        ),
        FastApi::Ineligible(_) => ".build(scope)".to_string(),
    };
    let _ = write!(
        out,
        "    {{\n        \
         let key = v8_string(scope, \"{}\")?;\n        \
         let method = v8::FunctionTemplate::builder(call_{snake}_{member}::<T>){signature_call}\n            .length({length})\n            {build};\n        \
         method.set_class_name(key);\n        \
         {target}.set_with_attr(key.into(), method.into(), v8::PropertyAttribute::NONE);\n    }}\n",
        group.name
    );
}

fn fast_struct(interface: &str, member: &str) -> String {
    format!("{interface}{}", naming::pascal_case(member))
}

fn constructor_callback(interface: &Interface, bound: &str, out: &mut String) {
    let name = &interface.name;
    let snake = naming::snake_stem(name);
    if interface.constructors.is_empty() {
        let _ = write!(
            out,
            "\n/// `{name}` declares no `constructor`, so calling it throws, as WebIDL\n\
             /// requires for an interface without a constructor operation.\n\
             fn construct_{snake}<'s, T: {bound} + 'static>(\n    \
             scope: &mut v8::PinScope<'s, '_>,\n    \
             _args: v8::FunctionCallbackArguments<'s>,\n    \
             _rv: v8::ReturnValue<v8::Value>,\n\
             ) {{\n    throw_type_error(scope, \"Illegal constructor\");\n}}\n"
        );
        return;
    }
    let _ = write!(
        out,
        "\n/// The `{name}` constructor.\n\
         fn construct_{snake}<'s, T: {bound} + 'static>(\n    \
         scope: &mut v8::PinScope<'s, '_>,\n    \
         args: v8::FunctionCallbackArguments<'s>,\n    \
         mut rv: v8::ReturnValue<v8::Value>,\n\
         ) {{\n    \
         if !args.is_construct_call() {{\n        \
         throw_type_error(\n            scope,\n            \"Failed to construct '{name}': please use the 'new' operator\",\n        );\n        return;\n    }}\n"
    );
    let constructor = &interface.constructors[0];
    let mut passes = Vec::new();
    for (index, argument) in constructor.arguments.iter().enumerate() {
        argument_binding(argument, index, "        ", out);
        passes.push(pass_expr(argument));
    }
    let required = constructor
        .arguments
        .iter()
        .filter(|a| !a.optional && !a.variadic)
        .count();
    if required > 0 {
        let _ = write!(
            out,
            "    if args.length() < {required} {{\n        throw_type_error(\n            scope,\n            \"Failed to construct '{name}': {required} argument(s) required\",\n        );\n        return;\n    }}\n"
        );
    }
    // The constructor receives the realm (host context) as its first argument
    // and adopts the `new`-allocated `this` into the world so the host gets a
    // finalizer and cached identity — the `this` object is kept (not replaced by
    // a fresh template instance) so `class Sub extends Interface` sees its own
    // prototype.
    let call_args = if passes.is_empty() {
        "&realm".to_owned()
    } else {
        format!("&realm, {}", passes.join(", "))
    };
    let _ = write!(
        out,
        "    let realm = match world_realm(scope) {{\n        \
         Ok(realm) => realm,\n        \
         Err(error) => {{\n            throw_js_error(scope, &error);\n            return;\n        }}\n    }};\n    \
         match <T as {}Constructor>::{}({}) {{\n        \
         Ok(host) => {{\n            \
         let this = args.this();\n            \
         if let Err(error) = adopt_host(scope, \"{}\", this, host) {{\n                throw_js_error(scope, &error);\n                return;\n            }}\n            \
         rv.set(this.into());\n        \
         }}\n        \
         Err(error) => throw_js_error(scope, &error),\n    }}\n}}\n",
        name, constructor.rust_name, call_args, name,
    );
}

fn attribute_callbacks(
    interface: &Interface,
    attribute: &Attribute,
    bound: &str,
    out: &mut String,
) {
    if attribute.is_static {
        attribute_callbacks_static(&interface.name, attribute, bound, out);
        return;
    }
    let name = &interface.name;
    let snake = naming::snake_stem(name);
    let member = naming::snake_stem(&attribute.name);
    let owned = rust_type(&attribute.ty, Position::Owned);

    // Getter.
    let _ = write!(
        out,
        "\n/// Getter for `{name}.{}`.\n\
         fn get_{snake}_{member}<'s, T: {bound} + 'static>(\n    \
         scope: &mut v8::PinScope<'s, '_>,\n    \
         args: v8::FunctionCallbackArguments<'s>,\n    \
         mut rv: v8::ReturnValue<v8::Value>,\n\
         ) {{\n{}",
        attribute.name,
        unwrap_this_block("    ")
    );
    match attribute.fast_getter {
        FastApi::Eligible => {
            let setter = convert::return_value_setter(&attribute.ty).unwrap_or("set");
            let cast = convert::return_value_cast(&attribute.ty);
            let _ = write!(
                out,
                "    rv.{setter}(host.{}(){cast});\n}}\n",
                attribute.getter_name
            );
        }
        FastApi::Ineligible(_) => {
            let _ = write!(
                out,
                "    let value: {owned} = match host.{}() {{\n        Ok(value) => value,\n        Err(error) => {{\n            throw_js_error(scope, &error);\n            return;\n        }}\n    }};\n",
                attribute.getter_name
            );
            let conversion = convert::to_v8(&attribute.ty, "scope", "value");
            let _ = write!(
                out,
                "    match {conversion} {{\n        Ok(value) => rv.set(value),\n        Err(error) => throw_js_error(scope, &error),\n    }}\n}}\n"
            );
        }
    }

    // Emit fast-accessor tables unconditionally (for both getter and setter if eligible).
    fast_accessor_tables(interface, attribute, bound, out);

    // Setter.
    if attribute.replaceable() {
        let _ = write!(
            out,
            "\n/// `[Replaceable]` setter for `{name}.{}`: defines an own data property\n\
             /// on the receiver, shadowing the accessor.\n\
             fn set_{snake}_{member}<'s, T: {bound} + 'static>(\n    \
             scope: &mut v8::PinScope<'s, '_>,\n    \
             args: v8::FunctionCallbackArguments<'s>,\n    \
             _rv: v8::ReturnValue<v8::Value>,\n\
             ) {{\n    \
             let this = args.this();\n    \
             let key = match v8_string(scope, \"{}\") {{\n        Ok(key) => key,\n        Err(error) => {{\n            throw_js_error(scope, &error);\n            return;\n        }}\n    }};\n    \
             let value = args.get(0);\n    \
             if this.create_data_property(scope, key.into(), value).is_none() {{\n        \
             throw_type_error(scope, \"cannot replace `{}`\");\n    }}\n}}\n",
            attribute.name, attribute.name, attribute.name
        );
        return;
    }
    if let Some(forward) = attribute.put_forwards() {
        let _ = write!(
            out,
            "\n/// `[PutForwards={forward}]` setter for `{name}.{}`: forwards the assignment\n\
             /// to the `{forward}` property of the object the getter returns.\n\
             fn set_{snake}_{member}<'s, T: {bound} + 'static>(\n    \
             scope: &mut v8::PinScope<'s, '_>,\n    \
             args: v8::FunctionCallbackArguments<'s>,\n    \
             _rv: v8::ReturnValue<v8::Value>,\n\
             ) {{\n    \
             let this = args.this();\n    \
             let key = match v8_string(scope, \"{}\") {{\n        Ok(key) => key,\n        Err(error) => {{\n            throw_js_error(scope, &error);\n            return;\n        }}\n    }};\n    \
             let Some(target) = this.get(scope, key.into()) else {{\n        \
             throw_type_error(scope, \"`{}` cannot be read\");\n        return;\n    }};\n    \
             let Ok(target) = TryInto::<v8::Local<v8::Object>>::try_into(target) else {{\n        \
             throw_type_error(scope, \"`{}` is not an object\");\n        return;\n    }};\n    \
             let forward = match v8_string(scope, \"{forward}\") {{\n        Ok(key) => key,\n        Err(error) => {{\n            throw_js_error(scope, &error);\n            return;\n        }}\n    }};\n    \
             let value = args.get(0);\n    \
             if target.set(scope, forward.into(), value).is_none() {{\n        \
             throw_type_error(scope, \"cannot forward the assignment to `{forward}`\");\n    }}\n}}\n",
            attribute.name, attribute.name, attribute.name, attribute.name
        );
        return;
    }
    let (Some(setter_name), Some(fast_setter)) = (&attribute.setter_name, attribute.fast_setter)
    else {
        return;
    };
    let _ = write!(
        out,
        "\n/// Setter for `{name}.{}`.\n\
         fn set_{snake}_{member}<'s, T: {bound} + 'static>(\n    \
         scope: &mut v8::PinScope<'s, '_>,\n    \
         args: v8::FunctionCallbackArguments<'s>,\n    \
         _rv: v8::ReturnValue<v8::Value>,\n\
         ) {{\n{}",
        attribute.name,
        unwrap_this_block("    ")
    );
    let conversion = convert::from_v8(&attribute.ty, "scope", "raw", IntegerMode::Modulo);
    let _ = write!(
        out,
        "    let raw = args.get(0);\n    \
         let value = match {conversion} {{\n        Ok(value) => value,\n        Err(error) => {{\n            throw_js_error(scope, &error);\n            return;\n        }}\n    }};\n"
    );
    let pass = borrow_expr(&attribute.ty, "value");
    match fast_setter {
        FastApi::Eligible => {
            let _ = write!(out, "    host.{setter_name}({pass});\n}}\n");
        }
        FastApi::Ineligible(_) => {
            let _ = write!(
                out,
                "    if let Err(error) = host.{setter_name}({pass}) {{\n        throw_js_error(scope, &error);\n    }}\n}}\n"
            );
        }
    }
}

fn attribute_callbacks_static(
    interface: &str,
    attribute: &Attribute,
    bound: &str,
    out: &mut String,
) {
    let snake = naming::snake_stem(interface);
    let member = naming::snake_stem(&attribute.name);
    let owned = rust_type(&attribute.ty, Position::Owned);
    let _ = write!(
        out,
        "\n/// Static getter for `{interface}.{}`.\n\
         fn get_{snake}_{member}<'s, T: {bound} + 'static>(\n    \
         scope: &mut v8::PinScope<'s, '_>,\n    \
         _args: v8::FunctionCallbackArguments<'s>,\n    \
         mut rv: v8::ReturnValue<v8::Value>,\n\
         ) {{\n    \
         let value: {owned} = match T::{}() {{\n        Ok(value) => value,\n        Err(error) => {{\n            throw_js_error(scope, &error);\n            return;\n        }}\n    }};\n",
        attribute.name, attribute.getter_name
    );
    let conversion = convert::to_v8(&attribute.ty, "scope", "value");
    let _ = write!(
        out,
        "    match {conversion} {{\n        Ok(value) => rv.set(value),\n        Err(error) => throw_js_error(scope, &error),\n    }}\n}}\n"
    );
    if let Some(setter_name) = &attribute.setter_name {
        let conversion = convert::from_v8(&attribute.ty, "scope", "raw", IntegerMode::Modulo);
        let pass = borrow_expr(&attribute.ty, "value");
        let _ = write!(
            out,
            "\n/// Static setter for `{interface}.{}`.\n\
             fn set_{snake}_{member}<'s, T: {bound} + 'static>(\n    \
             scope: &mut v8::PinScope<'s, '_>,\n    \
             args: v8::FunctionCallbackArguments<'s>,\n    \
             _rv: v8::ReturnValue<v8::Value>,\n\
             ) {{\n    \
             let raw = args.get(0);\n    \
             let value = match {conversion} {{\n        Ok(value) => value,\n        Err(error) => {{\n            throw_js_error(scope, &error);\n            return;\n        }}\n    }};\n    \
             if let Err(error) = T::{setter_name}({pass}) {{\n        throw_js_error(scope, &error);\n    }}\n}}\n",
            attribute.name
        );
    }
}

fn operation_callbacks(interface: &str, group: &OperationGroup, bound: &str, out: &mut String) {
    let snake = naming::snake_stem(interface);
    let member = naming::snake_stem(&group.name);
    if group.overloads.len() > 1 {
        let _ = write!(
            out,
            "\n/// Overload dispatcher for `{interface}.{}`; WebIDL selects an overload by\n\
             /// argument count first.\n\
             fn call_{snake}_{member}<'s, T: {bound} + 'static>(\n    \
             scope: &mut v8::PinScope<'s, '_>,\n    \
             args: v8::FunctionCallbackArguments<'s>,\n    \
             rv: v8::ReturnValue<v8::Value>,\n\
             ) {{\n    match args.length() {{\n",
            group.name
        );
        for (arity, index) in overload_dispatch(group) {
            let overload = &group.overloads[index];
            let _ = writeln!(
                out,
                "        {arity} => call_{snake}_{}::<T>(scope, args, rv),",
                naming::ident_stem(&overload.rust_name)
            );
        }
        let _ = write!(
            out,
            "        _ => throw_type_error(\n            scope,\n            \"Failed to execute '{}' on '{interface}': no overload matches the argument count\",\n        ),\n    }}\n}}\n",
            group.name
        );
        for overload in &group.overloads {
            operation_callback(interface, group, overload, bound, out);
        }
    } else {
        operation_callback(interface, group, &group.overloads[0], bound, out);
    }
    if group.fast.is_eligible() {
        fast_method_table(interface, group, bound, out);
    }
}

fn operation_callback(
    interface: &str,
    group: &OperationGroup,
    operation: &Operation,
    bound: &str,
    out: &mut String,
) {
    let snake = naming::snake_stem(interface);
    let function = format!("call_{snake}_{}", naming::ident_stem(&operation.rust_name));
    // A static operation with no arguments never reads the argument list.
    let args = if group.is_static && operation.arguments.is_empty() {
        "_args"
    } else {
        "args"
    };
    let _ = write!(
        out,
        "\n/// `{interface}.{}`.\n\
         fn {function}<'s, T: {bound} + 'static>(\n    \
         scope: &mut v8::PinScope<'s, '_>,\n    \
         {args}: v8::FunctionCallbackArguments<'s>,\n    \
         mut rv: v8::ReturnValue<v8::Value>,\n\
         ) {{\n",
        group.name
    );
    let required = operation.required_argument_count();
    if required > 0 {
        let _ = write!(
            out,
            "    if args.length() < {required} {{\n        throw_type_error(\n            scope,\n            \"Failed to execute '{}' on '{interface}': {required} argument(s) required\",\n        );\n        return;\n    }}\n",
            group.name
        );
    }
    if !group.is_static {
        out.push_str(&unwrap_this_block("    "));
    }
    let mut passes = Vec::new();
    for (index, argument) in operation.arguments.iter().enumerate() {
        argument_binding(argument, index, "    ", out);
        passes.push(pass_expr(argument));
    }
    let receiver = if group.is_static { "T::" } else { "host." };
    let call = format!("{receiver}{}({})", operation.rust_name, passes.join(", "));
    match operation.fast {
        FastApi::Eligible if operation.return_type == Type::Undefined => {
            let _ = write!(out, "    {call};\n    rv.set_undefined();\n}}\n");
        }
        FastApi::Eligible => {
            let setter = convert::return_value_setter(&operation.return_type).unwrap_or("set");
            let cast = convert::return_value_cast(&operation.return_type);
            let _ = write!(out, "    rv.{setter}({call}{cast});\n}}\n");
        }
        FastApi::Ineligible(_) => {
            let owned = rust_type(&operation.return_type, Position::Owned);
            let _ = write!(
                out,
                "    let value: {owned} = match {call} {{\n        Ok(value) => value,\n        Err(error) => {{\n            throw_js_error(scope, &error);\n            return;\n        }}\n    }};\n"
            );
            if operation.return_type == Type::Undefined {
                out.push_str("    let () = value;\n    rv.set_undefined();\n}\n");
            } else {
                let conversion = convert::to_v8(&operation.return_type, "scope", "value");
                let _ = write!(
                    out,
                    "    match {conversion} {{\n        Ok(value) => rv.set(value),\n        Err(error) => throw_js_error(scope, &error),\n    }}\n}}\n"
                );
            }
        }
    }
}

fn indexed_getter_callback(interface: &str, operation: &Operation, bound: &str, out: &mut String) {
    let snake = naming::snake_stem(interface);
    let owned = rust_type(&operation.return_type, Position::Owned);
    let call = format!("host.{}(index)", operation.rust_name);
    let _ = write!(
        out,
        "\n/// Indexed property getter for `{interface}`, installed with\n\
         /// `ObjectTemplate::set_indexed_property_handler`.\n\
         fn indexed_get_{snake}<'s, T: {bound} + 'static>(\n    \
         scope: &mut v8::PinScope<'s, '_>,\n    \
         index: u32,\n    \
         args: v8::PropertyCallbackArguments<'s>,\n    \
         mut rv: v8::ReturnValue<v8::Value>,\n\
         ) -> v8::Intercepted {{\n    \
         let this = args.holder();\n    \
         // SAFETY: the indexed handler is installed on the interface's own\n    \
         // instance template, so the holder is an instance of it.\n    \
         let Some(host) = (unsafe {{ unwrap_receiver::<T>(this) }}) else {{\n        \
         return v8::Intercepted::kNo;\n    }};\n"
    );
    if operation.fast.is_eligible() {
        let setter = convert::return_value_setter(&operation.return_type).unwrap_or("set");
        let cast = convert::return_value_cast(&operation.return_type);
        let _ = write!(
            out,
            "    rv.{setter}({call}{cast});\n    v8::Intercepted::kYes\n}}\n"
        );
    } else {
        let conversion = convert::to_v8(&operation.return_type, "scope", "value");
        let _ = write!(
            out,
            "    let value: {owned} = match {call} {{\n        Ok(value) => value,\n        Err(error) => {{\n            throw_js_error(scope, &error);\n            return v8::Intercepted::kYes;\n        }}\n    }};\n    \
             match {conversion} {{\n        Ok(value) => rv.set(value),\n        Err(error) => throw_js_error(scope, &error),\n    }}\n    v8::Intercepted::kYes\n}}\n"
        );
    }
}

fn unwrap_this_block(indent: &str) -> String {
    format!(
        "{indent}let this = args.this();\n\
         {indent}// SAFETY: the template carries the interface signature, so V8 has\n\
         {indent}// already checked that the receiver is an instance of it and that its\n\
         {indent}// host field was written by `attach_host::<T>`.\n\
         {indent}let host = match unsafe {{ unwrap_this::<T>(&this) }} {{\n\
         {indent}    Ok(host) => host,\n\
         {indent}    Err(error) => {{\n\
         {indent}        throw_js_error(scope, &error);\n\
         {indent}        return;\n\
         {indent}    }}\n\
         {indent}}};\n"
    )
}

/// Emits the `let` bindings that convert one argument, and nothing else.
fn argument_binding(argument: &Argument, index: usize, indent: &str, out: &mut String) {
    let name = &argument.rust_name;
    let mode = IntegerMode::of(argument);
    if argument.variadic {
        let conversion = convert::from_v8(&argument.ty, "scope", "raw", mode);
        let _ = write!(
            out,
            "{indent}let mut {name} = Vec::new();\n\
             {indent}for position in {index}..args.length() {{\n\
             {indent}    let raw = args.get(position);\n\
             {indent}    match {conversion} {{\n\
             {indent}        Ok(value) => {name}.push(value),\n\
             {indent}        Err(error) => {{\n\
             {indent}            throw_js_error(scope, &error);\n\
             {indent}            return;\n\
             {indent}        }}\n\
             {indent}    }}\n\
             {indent}}}\n"
        );
        return;
    }
    let conversion = convert::from_v8(&argument.ty, "scope", "raw", mode);
    if argument.optional {
        let default = optional_default(argument);
        let _ = write!(
            out,
            "{indent}let {name} = if args.length() > {index} && !args.get({index}).is_undefined() {{\n\
             {indent}    let raw = args.get({index});\n\
             {indent}    match {conversion} {{\n\
             {indent}        Ok(value) => Some(value),\n\
             {indent}        Err(error) => {{\n\
             {indent}            throw_js_error(scope, &error);\n\
             {indent}            return;\n\
             {indent}        }}\n\
             {indent}    }}\n\
             {indent}}} else {{\n\
             {indent}    {default}\n\
             {indent}}};\n"
        );
        return;
    }
    let _ = write!(
        out,
        "{indent}let {name} = {{\n\
         {indent}    let raw = args.get({index});\n\
         {indent}    match {conversion} {{\n\
         {indent}        Ok(value) => value,\n\
         {indent}        Err(error) => {{\n\
         {indent}            throw_js_error(scope, &error);\n\
         {indent}            return;\n\
         {indent}        }}\n\
         {indent}    }}\n\
         {indent}}};\n"
    );
}

/// The `else` branch of an optional argument: the IDL default when it can be
/// spelled in Rust, `None` otherwise.
fn optional_default(argument: &Argument) -> String {
    let Some(default) = &argument.default else {
        return "None".to_string();
    };
    match default {
        DefaultValue::EmptyDictionary
            if !matches!(argument.ty.unwrap_nullable(), Type::Dictionary(_)) =>
        {
            "None".to_string()
        }
        DefaultValue::Null if !matches!(argument.ty, Type::Nullable(_)) => "None".to_string(),
        other => format!("Some({})", default_expr(&argument.ty, other)),
    }
}

/// Converts an owned binding to the borrowed form the trait method expects.
fn pass_expr(argument: &Argument) -> String {
    let name = &argument.rust_name;
    if argument.variadic {
        return name.clone();
    }
    if argument.optional {
        return match &argument.ty {
            ty if is_string(ty) => format!("{name}.as_deref()"),
            Type::Nullable(inner) if is_string(inner) => {
                format!("{name}.map(|inner| inner.as_deref())")
            }
            _ => name.clone(),
        };
    }
    borrow_expr(&argument.ty, name)
}

fn borrow_expr(ty: &Type, name: &str) -> String {
    match ty {
        ty if is_string(ty) => format!("&{name}"),
        Type::Nullable(inner) if is_string(inner) => format!("{name}.as_deref()"),
        _ => name.to_string(),
    }
}

fn is_string(ty: &Type) -> bool {
    matches!(ty, Type::DomString | Type::UsvString | Type::ByteString)
}

/// Maps each accepted argument count of an overload set to the overload that
/// handles it. The first declared overload wins a tie.
fn overload_dispatch(group: &OperationGroup) -> Vec<(String, usize)> {
    let mut assignment: Vec<(usize, usize)> = Vec::new();
    let mut catch_all: Option<usize> = None;
    for (index, overload) in group.overloads.iter().enumerate() {
        let classes = overload.arity_classes();
        if classes.contains(&usize::MAX) {
            catch_all.get_or_insert(index);
            continue;
        }
        for arity in classes {
            if !assignment.iter().any(|(existing, _)| *existing == arity) {
                assignment.push((arity, index));
            }
        }
    }
    assignment.sort_unstable();
    let mut arms: Vec<(String, usize)> = Vec::new();
    for (arity, index) in assignment {
        match arms.last_mut() {
            Some((pattern, existing)) if *existing == index => {
                let _ = write!(pattern, " | {arity}");
            }
            _ => arms.push((arity.to_string(), index)),
        }
    }
    if let Some(index) = catch_all {
        arms.push(("_".to_string(), index));
    }
    arms
}

// -- fast API tables --------------------------------------------------------

fn fast_accessor_tables(
    interface: &Interface,
    attribute: &Attribute,
    bound: &str,
    out: &mut String,
) {
    let name = &interface.name;
    let snake = naming::snake_stem(name);
    let member = naming::snake_stem(&attribute.name);
    let base = fast_struct(name, &attribute.name);
    if attribute.fast_getter.is_eligible() {
        let return_type = fast_api_rust_type(&attribute.ty);
        let fallback = fallback_value(&attribute.ty);
        let call = fast_return_convert(&attribute.ty, &format!("host.{}()", attribute.getter_name));
        let _ = write!(
            out,
            "\n/// Fast-API getter for `{name}.{}`.\n\
             extern \"C\" fn fast_get_{snake}_{member}<T: {bound} + 'static>(\n    \
             receiver: v8::Local<v8::Object>,\n\
             ) -> {return_type} {{\n    \
             // SAFETY: the fast callback is only reachable through a template that\n    \
             // carries the interface signature, so the receiver is an instance.\n    \
             match unsafe {{ unwrap_receiver::<T>(receiver) }} {{\n        \
             Some(host) => {call},\n        \
             None => {fallback},\n    }}\n}}\n",
            attribute.name
        );
        let _ = write!(
            out,
            "\n/// Fast-call table for the `{name}.{}` getter.\n\
             struct {base}Getter<T: {bound} + 'static>(core::marker::PhantomData<T>);\n\
             \n\
             impl<T: {bound} + 'static> {base}Getter<T> {{\n    \
             const TABLE: [v8::fast_api::CFunction; 1] = [v8::fast_api::CFunction::new(\n        \
             fast_get_{snake}_{member}::<T> as *const std::ffi::c_void,\n        \
             &v8::fast_api::CFunctionInfo::new(\n            \
             v8::fast_api::Type::{}.as_info(),\n            \
             &[v8::fast_api::Type::V8Value.as_info()],\n            \
             v8::fast_api::Int64Representation::Number,\n        ),\n    )];\n}}\n",
            attribute.name,
            fast_api_type(&attribute.ty)
        );
    }
    if attribute.fast_setter == Some(FastApi::Eligible)
        && let Some(setter_name) = &attribute.setter_name
    {
        let value_type = fast_api_rust_type(&attribute.ty);
        let (binding, pass) = if is_string(&attribute.ty) {
            (
                "    // SAFETY: V8 passes a live `FastOneByteString` for the call.\n    let text = unsafe { &*value }.as_bytes();\n    let text = String::from_utf8_lossy(text);\n"
                    .to_string(),
                "&text".to_string(),
            )
        } else {
            (
                String::new(),
                fast_argument_convert(&attribute.ty, false, "value"),
            )
        };
        let _ = write!(
            out,
            "\n/// Fast-API setter for `{name}.{}`.\n\
             extern \"C\" fn fast_set_{snake}_{member}<T: {bound} + 'static>(\n    \
             receiver: v8::Local<v8::Object>,\n    \
             value: {value_type},\n\
             ) {{\n{binding}    \
             // SAFETY: as for the fast getter.\n    \
             if let Some(host) = unsafe {{ unwrap_receiver::<T>(receiver) }} {{\n        \
             host.{setter_name}({pass});\n    }}\n}}\n",
            attribute.name
        );
        let _ = write!(
            out,
            "\n/// Fast-call table for the `{name}.{}` setter.\n\
             struct {base}Setter<T: {bound} + 'static>(core::marker::PhantomData<T>);\n\
             \n\
             impl<T: {bound} + 'static> {base}Setter<T> {{\n    \
             const TABLE: [v8::fast_api::CFunction; 1] = [v8::fast_api::CFunction::new(\n        \
             fast_set_{snake}_{member}::<T> as *const std::ffi::c_void,\n        \
             &v8::fast_api::CFunctionInfo::new(\n            \
             v8::fast_api::Type::Void.as_info(),\n            \
             &[\n                v8::fast_api::Type::V8Value.as_info(),\n                {},\n            ],\n            \
             v8::fast_api::Int64Representation::Number,\n        ),\n    )];\n}}\n",
            attribute.name,
            ctype_info(&attribute.ty, IntegerMode::Modulo)
        );
    }
}

fn fast_method_table(interface: &str, group: &OperationGroup, bound: &str, out: &mut String) {
    let snake = naming::snake_stem(interface);
    let member = naming::snake_stem(&group.name);
    let operation = &group.overloads[0];
    let base = fast_struct(interface, &group.name);
    let mut parameters = vec!["    receiver: v8::Local<v8::Object>,".to_string()];
    let mut bindings = String::new();
    let mut passes = Vec::new();
    let mut infos = vec!["                v8::fast_api::Type::V8Value.as_info(),".to_string()];
    for argument in &operation.arguments {
        let ty = fast_api_rust_type(&argument.ty);
        parameters.push(format!("    {}: {ty},", argument.rust_name));
        if is_string(&argument.ty) {
            let _ = write!(
                bindings,
                "    // SAFETY: V8 passes a live `FastOneByteString` for the call.\n    let {0} = unsafe {{ &*{0} }}.as_bytes();\n    let {0} = String::from_utf8_lossy({0});\n",
                argument.rust_name
            );
            passes.push(format!("&{}", argument.rust_name));
        } else {
            passes.push(fast_argument_convert(
                &argument.ty,
                argument.clamp(),
                &argument.rust_name,
            ));
        }
        infos.push(format!(
            "                {},",
            ctype_info(&argument.ty, IntegerMode::of(argument))
        ));
    }
    let return_clause = if operation.return_type == Type::Undefined {
        String::new()
    } else {
        format!(" -> {}", fast_api_rust_type(&operation.return_type))
    };
    let fallback = fallback_value(&operation.return_type);
    let call = fast_return_convert(
        &operation.return_type,
        &format!("host.{}({})", operation.rust_name, passes.join(", ")),
    );
    let _ = write!(
        out,
        "\n/// Fast-API callback for `{interface}.{}`.\n\
         extern \"C\" fn fast_call_{snake}_{member}<T: {bound} + 'static>(\n{}\n){return_clause} {{\n{bindings}    \
         // SAFETY: the fast callback is only reachable through a template that\n    \
         // carries the interface signature, so the receiver is an instance.\n    \
         match unsafe {{ unwrap_receiver::<T>(receiver) }} {{\n        \
         Some(host) => {call},\n        \
         None => {fallback},\n    }}\n}}\n",
        group.name,
        parameters.join("\n"),
    );
    let _ = write!(
        out,
        "\n/// Fast-call table for `{interface}.{}`.\n\
         struct {base}Method<T: {bound} + 'static>(core::marker::PhantomData<T>);\n\
         \n\
         impl<T: {bound} + 'static> {base}Method<T> {{\n    \
         const TABLE: [v8::fast_api::CFunction; 1] = [v8::fast_api::CFunction::new(\n        \
         fast_call_{snake}_{member}::<T> as *const std::ffi::c_void,\n        \
         &v8::fast_api::CFunctionInfo::new(\n            \
         v8::fast_api::Type::{}.as_info(),\n            \
         &[\n{}\n            ],\n            \
         v8::fast_api::Int64Representation::Number,\n        ),\n    )];\n}}\n",
        group.name,
        fast_api_type(&operation.return_type),
        infos.join("\n")
    );
}

/// The `CTypeInfo` expression for an argument, carrying `[Clamp]` and
/// `[EnforceRange]` as V8 flags.
fn ctype_info(ty: &Type, mode: IntegerMode) -> String {
    let variant = fast_api_type(ty);
    match mode {
        IntegerMode::Modulo => format!("v8::fast_api::Type::{variant}.as_info()"),
        IntegerMode::Clamp => format!(
            "v8::fast_api::CTypeInfo::new(v8::fast_api::Type::{variant}, v8::fast_api::Flags::Clamp)"
        ),
        IntegerMode::EnforceRange => format!(
            "v8::fast_api::CTypeInfo::new(v8::fast_api::Type::{variant}, v8::fast_api::Flags::EnforceRange)"
        ),
    }
}

/// The value a fast callback returns when the receiver has no host object.
fn fallback_value(ty: &Type) -> String {
    match ty {
        Type::Undefined => "()".to_string(),
        Type::Boolean => "false".to_string(),
        Type::Float { .. } | Type::Double { .. } => "0.0".to_string(),
        _ => "0".to_string(),
    }
}
