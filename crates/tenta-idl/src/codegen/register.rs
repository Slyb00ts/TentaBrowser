//! The registry entry points: one descriptor and one `register_*` per
//! interface or namespace.

use std::fmt::Write as _;

use crate::codegen::rust_type::float_literal;
use crate::model::{
    ConstValue, Constant, Exposure, FastApi, Interface, Member, Model, Namespace, PropertyKey,
};
use crate::naming;

/// Generates `<snake>_register.rs` for an interface.
pub fn interface_register(_model: &Model, interface: &Interface) -> String {
    let name = &interface.name;
    let parent = match &interface.parent {
        Some(parent) => format!("Some(\"{parent}\")"),
        None => "None".to_string(),
    };
    let constructor_length = match interface.constructor_length() {
        Some(length) => format!("Some({length})"),
        None => "None".to_string(),
    };
    let iterable = match &interface.iterable {
        Some(iterable) => format!("Some(\"{}\")", iterable.value.idl_name()),
        None => "None".to_string(),
    };
    descriptor(
        name,
        "Interface",
        &parent,
        &interface.exposure,
        &constructor_length,
        &interface.constants,
        &interface.members,
        &interface.property_enumeration_order(),
        &iterable,
    )
}

/// Generates `<snake>_register.rs` for a namespace.
pub fn namespace_register(_model: &Model, namespace: &Namespace) -> String {
    descriptor(
        &namespace.name,
        "Namespace",
        "None",
        &namespace.exposure,
        "None",
        &namespace.constants,
        &namespace.members,
        &namespace.property_enumeration_order(),
        "None",
    )
}

#[allow(clippy::too_many_arguments)]
fn descriptor(
    name: &str,
    kind: &str,
    parent: &str,
    exposure: &Exposure,
    constructor_length: &str,
    constants: &[Constant],
    members: &[Member],
    order: &[PropertyKey],
    iterable: &str,
) -> String {
    let snake = naming::snake_stem(name);
    let upper = naming::screaming_snake_case(name);
    let mut out = String::new();
    let _ = write!(
        out,
        "// Registry entry point for `{name}`.\n\
         //\n\
         // Generated by `tenta-idl`; do not edit.\n"
    );

    let _ = write!(
        out,
        "\n/// Constants of `{name}`, in definition order.\n\
         pub static {upper}_CONSTANTS: [ConstantDescriptor; {}] = [\n",
        constants.len()
    );
    for constant in constants {
        let value = match &constant.value {
            ConstValue::Boolean(value) => format!("ConstantValue::Boolean({value})"),
            ConstValue::Integer(value) => format!("ConstantValue::Integer({value})"),
            ConstValue::Float(value) => {
                format!("ConstantValue::Float({})", float_literal(*value))
            }
            ConstValue::Null => "ConstantValue::Null".to_string(),
        };
        let _ = write!(
            out,
            "    ConstantDescriptor {{\n        name: \"{}\",\n        value: {value},\n    }},\n",
            constant.name
        );
    }
    out.push_str("];\n");

    let attributes: Vec<_> = members
        .iter()
        .filter_map(|m| match m {
            Member::Attribute(attribute) => Some(attribute),
            _ => None,
        })
        .collect();
    let _ = write!(
        out,
        "\n/// Attributes of `{name}`, in definition order.\n\
         pub static {upper}_ATTRIBUTES: [AttributeDescriptor; {}] = [\n",
        attributes.len()
    );
    for attribute in &attributes {
        let _ = write!(
            out,
            "    AttributeDescriptor {{\n        name: \"{}\",\n        readonly: {},\n        is_static: {},\n        fast_getter: {},\n        fast_setter: {},\n        extended_attributes: &[{}],\n    }},\n",
            attribute.name,
            attribute.readonly,
            attribute.is_static,
            attribute.fast_getter.is_eligible(),
            attribute
                .fast_setter
                .map(FastApi::is_eligible)
                .unwrap_or(false),
            quoted(&attribute.attrs.names()),
        );
    }
    out.push_str("];\n");

    let operations: Vec<_> = members
        .iter()
        .filter_map(|m| match m {
            Member::Operation(group) => Some(group),
            _ => None,
        })
        .collect();
    let _ = write!(
        out,
        "\n/// Operations of `{name}`, in definition order.\n\
         pub static {upper}_OPERATIONS: [OperationDescriptor; {}] = [\n",
        operations.len()
    );
    for group in &operations {
        let length = group
            .overloads
            .iter()
            .map(|o| o.required_argument_count())
            .min()
            .unwrap_or(0);
        let _ = write!(
            out,
            "    OperationDescriptor {{\n        name: \"{}\",\n        is_static: {},\n        length: {length},\n        overloads: {},\n        fast: {},\n        extended_attributes: &[{}],\n    }},\n",
            group.name,
            group.is_static,
            group.overloads.len(),
            group.fast.is_eligible(),
            quoted(&group.overloads[0].attrs.names()),
        );
    }
    out.push_str("];\n");

    let order_names: Vec<&str> = order.iter().map(PropertyKey::js_name).collect();
    let _ = write!(
        out,
        "\n/// The WebIDL property enumeration order of `{name}`: constants first,\n\
         /// then attributes and operations in definition order, then\n\
         /// `Symbol.toStringTag`.\n\
         pub static {upper}_ENUMERATION_ORDER: [&str; {}] = [{}];\n",
        order_names.len(),
        quoted(&order_names),
    );

    let exposure_names = exposure.names();
    let _ = write!(
        out,
        "\n/// The descriptor `register_{snake}` hands to the registry.\n\
         pub static {upper}_DESCRIPTOR: InterfaceDescriptor = InterfaceDescriptor {{\n    \
         name: \"{name}\",\n    \
         kind: DefinitionKind::{kind},\n    \
         parent: {parent},\n    \
         exposure: &[{}],\n    \
         constructor_length: {constructor_length},\n    \
         constants: &{upper}_CONSTANTS,\n    \
         attributes: &{upper}_ATTRIBUTES,\n    \
         operations: &{upper}_OPERATIONS,\n    \
         enumeration_order: &{upper}_ENUMERATION_ORDER,\n    \
         iterable_value: {iterable},\n\
         }};\n",
        quoted(&exposure_names),
    );

    let _ = write!(
        out,
        "\n/// Registers `{name}` with `registry`.\n\
         ///\n\
         /// Registration only records the descriptor; the prototype is built on\n\
         /// first access in a context (`docs/spec/02-architecture.md` §2.1).\n\
         pub fn register_{snake}(registry: &mut dyn InterfaceRegistry) {{\n    \
         registry.register({upper}_DESCRIPTOR);\n}}\n"
    );
    out
}

fn quoted(values: &[&str]) -> String {
    values
        .iter()
        .map(|value| format!("\"{value}\""))
        .collect::<Vec<_>>()
        .join(", ")
}
