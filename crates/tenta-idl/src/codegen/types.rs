//! The shared type module: interface markers, typedef aliases, enumerations,
//! dictionaries, unions and callback aliases for one model.

use std::fmt::Write as _;

use crate::codegen::convert::{self, IntegerMode};
use crate::codegen::rust_type::{Position, default_expr, rust_type};
use crate::model::{
    BufferType, Dictionary, DictionaryMember, Enum, Model, Type, Union, UnionMember,
};

/// Generates `types.rs`.
pub fn types(model: &Model) -> String {
    let mut out = String::new();
    out.push_str(
        "// Shared WebIDL types for this binding module.\n\
         //\n\
         // Generated by `tenta-idl`; do not edit. Include after `prelude.rs`.\n",
    );
    markers(model, &mut out);
    typedefs(model, &mut out);
    for enumeration in &model.enums {
        enumeration_code(enumeration, &mut out);
    }
    for dictionary in &model.dictionaries {
        dictionary_code(model, dictionary, &mut out);
    }
    for union in &model.unions {
        union_code(union, &mut out);
    }
    callbacks(model, &mut out);
    out
}

fn markers(model: &Model, out: &mut String) {
    let mut names: Vec<&str> = model.interfaces.iter().map(|i| i.name.as_str()).collect();
    names.extend(model.opaque_interfaces.iter().map(String::as_str));
    names.sort_unstable();
    names.dedup();
    if names.is_empty() {
        return;
    }
    out.push_str("\n// Interface marker types. `Handle<Node>` names a host object of interface\n// `Node`; the marker itself is uninhabited and only carries the name.\n");
    for name in names {
        let defined = model.interface(name).is_some();
        let note = if defined {
            "defined in this module"
        } else {
            "declared elsewhere"
        };
        let _ = write!(
            out,
            "\n/// Marker for the WebIDL interface `{name}` ({note}).\n\
             pub enum {name} {{}}\n\
             \n\
             impl InterfaceMarker for {name} {{\n    \
             const INTERFACE_NAME: &'static str = \"{name}\";\n\
             }}\n"
        );
    }
}

fn typedefs(model: &Model, out: &mut String) {
    if model.typedefs.is_empty() {
        return;
    }
    out.push_str(
        "\n// Typedef aliases. The alias uses the owned spelling of the type; an\n\
         // argument position uses `&str` where the alias says `String`.\n",
    );
    for typedef in &model.typedefs {
        let _ = write!(
            out,
            "\n/// `typedef {} {};`\npub type {} = {};\n",
            typedef.ty.idl_name(),
            typedef.name,
            typedef.name,
            rust_type(&typedef.ty, Position::Owned),
        );
    }
}

fn enumeration_code(enumeration: &Enum, out: &mut String) {
    let name = &enumeration.name;
    let _ = write!(
        out,
        "\n/// WebIDL `enum {name}`.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n\
         pub enum {name} {{\n"
    );
    for value in &enumeration.values {
        let _ = write!(
            out,
            "    /// `\"{}\"`\n    {},\n",
            value.value, value.rust_name
        );
    }
    out.push_str("}\n");

    let values = enumeration
        .values
        .iter()
        .map(|v| format!("{name}::{}", v.rust_name))
        .collect::<Vec<_>>()
        .join(", ");
    let _ = write!(
        out,
        "\nimpl {name} {{\n    \
         /// Every value of the enumeration, in definition order.\n    \
         pub const VALUES: &'static [{name}] = &[{values}];\n\
         \n    \
         /// The JavaScript string this value maps to.\n    \
         pub fn as_str(&self) -> &'static str {{\n        match self {{\n"
    );
    for value in &enumeration.values {
        let _ = writeln!(
            out,
            "            {name}::{} => \"{}\",",
            value.rust_name, value.value
        );
    }
    out.push_str("        }\n    }\n\n    /// Parses a JavaScript string; `None` for a value outside the enumeration.\n    pub fn parse(value: &str) -> Option<Self> {\n        match value {\n");
    for value in &enumeration.values {
        let _ = writeln!(
            out,
            "            \"{}\" => Some({name}::{}),",
            value.value, value.rust_name
        );
    }
    out.push_str("            _ => None,\n        }\n    }\n}\n");

    let _ = write!(
        out,
        "\n#[cfg(feature = \"v8\")]\nimpl {name} {{\n    \
         /// Converts a JavaScript value to this enumeration.\n    \
         pub fn from_v8(\n        scope: &mut v8::PinScope<'_, '_>,\n        value: v8::Local<v8::Value>,\n    ) -> Result<Self, JsError> {{\n        \
         let text = string_from_v8(scope, value)?;\n        \
         Self::parse(&text)\n            .ok_or_else(|| JsError::type_error(\"the value is not a member of enum {name}\"))\n    }}\n\
         \n    \
         /// Converts this enumeration to a JavaScript string.\n    \
         pub fn to_v8<'s>(\n        &self,\n        scope: &mut v8::PinScope<'s, '_>,\n    ) -> Result<v8::Local<'s, v8::Value>, JsError> {{\n        \
         string_to_v8(scope, self.as_str())\n    }}\n}}\n"
    );

    let _ = write!(
        out,
        "\n#[cfg(feature = \"quickjs\")]\nimpl<'js> rquickjs::FromJs<'js> for {name} {{\n    \
         fn from_js(ctx: &rquickjs::Ctx<'js>, value: rquickjs::Value<'js>) -> rquickjs::Result<Self> {{\n        \
         let text: String = rquickjs::FromJs::from_js(ctx, value)?;\n        \
         Self::parse(&text).ok_or_else(|| {{\n            \
         rquickjs::Exception::throw_type(ctx, \"the value is not a member of enum {name}\")\n        }})\n    }}\n}}\n\
         \n#[cfg(feature = \"quickjs\")]\nimpl<'js> rquickjs::IntoJs<'js> for {name} {{\n    \
         fn into_js(self, ctx: &rquickjs::Ctx<'js>) -> rquickjs::Result<rquickjs::Value<'js>> {{\n        \
         rquickjs::IntoJs::into_js(self.as_str(), ctx)\n    }}\n}}\n"
    );
}

/// The Rust field type of a dictionary member.
fn member_type(member: &DictionaryMember) -> String {
    let base = rust_type(&member.ty, Position::Owned);
    if member.required || member.default.is_some() {
        base
    } else {
        format!("Option<{base}>")
    }
}

fn member_default(member: &DictionaryMember) -> String {
    match &member.default {
        Some(default) => default_expr(&member.ty, default),
        None if member.required => "Default::default()".to_string(),
        None => "None".to_string(),
    }
}

/// True when a member's WebIDL default is the value `#[derive(Default)]`
/// would produce, so the explicit `impl Default` can be dropped.
///
/// `String::from("")` is on the list because that is what
/// `default_expr` emits for a string member defaulted with `""`, and it is
/// `String::new()` under another spelling. Missing it made every dictionary
/// whose members are all defaulted to the empty string take the manual path,
/// which `clippy::derivable_impls` then rejects — `BlobPropertyBag` and
/// `FilePropertyBag` were the first such pair.
fn is_rust_default(expression: &str) -> bool {
    matches!(
        expression,
        "None"
            | "Default::default()"
            | "false"
            | "0"
            | "0.0"
            | "String::new()"
            | "String::from(\"\")"
            | "Vec::new()"
    )
}

fn dictionary_code(model: &Model, dictionary: &Dictionary, out: &mut String) {
    let name = &dictionary.name;
    let members = model.dictionary_members(name);
    let conversion_members = model.dictionary_conversion_members(name);
    let inherited = match &dictionary.parent {
        Some(parent) => format!(" : {parent}"),
        None => String::new(),
    };
    let derived_default = members
        .iter()
        .all(|member| is_rust_default(&member_default(member)));
    let derives = if derived_default {
        "#[derive(Debug, Clone, PartialEq, Default)]"
    } else {
        "#[derive(Debug, Clone, PartialEq)]"
    };
    let _ = write!(
        out,
        "\n/// WebIDL `dictionary {name}{inherited}`.\n\
         ///\n\
         /// Inherited members come first, then the members this dictionary\n\
         /// declares, in definition order.\n\
         {derives}\n\
         pub struct {name} {{\n"
    );
    for member in &members {
        let required = if member.required { "required " } else { "" };
        let default = match &member.default {
            Some(default) => format!(" = {}", crate::codegen::ops::default_literal(default)),
            None => String::new(),
        };
        let _ = write!(
            out,
            "    /// `{required}{} {}{default};`\n    pub {}: {},\n",
            member.ty.idl_name(),
            member.name,
            member.rust_name,
            member_type(member),
        );
    }
    out.push_str("}\n");

    if !derived_default {
        let _ = write!(
            out,
            "\nimpl Default for {name} {{\n    fn default() -> Self {{\n        Self {{\n"
        );
        for member in &members {
            let _ = writeln!(
                out,
                "            {}: {},",
                member.rust_name,
                member_default(member)
            );
        }
        out.push_str("        }\n    }\n}\n");
    }

    dictionary_v8(&members, &conversion_members, name, out);
    dictionary_quickjs(&members, &conversion_members, name, out);
}

fn dictionary_v8(
    members: &[&DictionaryMember],
    conversion_members: &[&DictionaryMember],
    name: &str,
    out: &mut String,
) {
    // WebIDL's *convert to a dictionary* ends at undefined or null for a
    // dictionary the caller passed nothing for, so an empty dictionary is the
    // value — and a `required` member then makes the conversion a `TypeError`
    // (https://webidl.spec.whatwg.org/#es-dictionary). Returning the default
    // here would skip those checks, which is why the early return is emitted only
    // for a dictionary that has nothing required in it. A dictionary with a
    // required member falls through to the object conversion, whose `try_into`
    // raises the same `TypeError` for `undefined`, and `new StaticRange()` — the
    // case `StaticRange-constructor.html` pins — throws instead of constructing a
    // range over whatever the zero handle happened to name.
    let early_return = if members.iter().any(|member| member.required) {
        String::new()
    } else {
        "        if value.is_null_or_undefined() {\n            return Ok(result);\n        }\n"
            .to_owned()
    };
    let _ = write!(
        out,
        "\n#[cfg(feature = \"v8\")]\nimpl {name} {{\n    \
         /// Converts a JavaScript value to this dictionary.\n    \
         pub fn from_v8(\n        scope: &mut v8::PinScope<'_, '_>,\n        value: v8::Local<v8::Value>,\n    ) -> Result<Self, JsError> {{\n        \
         let mut result = Self::default();\n{early_return}        \
         let object: v8::Local<v8::Object> = value\n            .try_into()\n            .map_err(|_| JsError::type_error(\"expected a dictionary for `{name}`\"))?;\n"
    );
    for member in conversion_members {
        let conversion = convert::from_v8(&member.ty, "scope", "member", IntegerMode::Modulo);
        let conversion =
            convert::legacy_null_to_empty(&member.ty, &member.attrs, "member", conversion);
        let assign = if member.required || member.default.is_some() {
            format!("result.{} = ({conversion})?;", member.rust_name)
        } else {
            format!("result.{} = Some(({conversion})?);", member.rust_name)
        };
        let _ = write!(
            out,
            "        if let Some(member) = dictionary_member(scope, object, \"{}\")? {{\n            {assign}\n        }}",
            member.name
        );
        if member.required {
            let _ = write!(
                out,
                " else {{\n            return Err(JsError::type_error(\n                \"`{name}` requires the member `{}`\",\n            ));\n        }}",
                member.name
            );
        }
        out.push('\n');
    }
    out.push_str("        Ok(result)\n    }\n");

    let _ = write!(
        out,
        "\n    /// Converts this dictionary to a JavaScript object.\n    \
         pub fn to_v8<'s>(\n        &self,\n        scope: &mut v8::PinScope<'s, '_>,\n    ) -> Result<v8::Local<'s, v8::Value>, JsError> {{\n        \
         let object = v8::Object::new(scope);\n"
    );
    for member in conversion_members {
        let optional = !member.required && member.default.is_none();
        let owned = if optional {
            if is_copy(&member.ty) {
                "*inner".to_owned()
            } else {
                "inner.clone()".to_owned()
            }
        } else {
            field_expr(&member.ty, &format!("self.{}", member.rust_name))
        };
        let conversion = convert::to_v8(&member.ty, "scope", "member");
        let open = if optional {
            format!(
                "        if let Some(inner) = &self.{} {{\n",
                member.rust_name
            )
        } else {
            "        {\n".to_owned()
        };
        let _ = write!(
            out,
            "{open}            let member = {owned};\n            let key = v8_string(scope, \"{}\")?;\n            let value = ({conversion})?;\n            let defined = object\n                .create_data_property(scope, key.into(), value)\n                .ok_or_else(JsError::pending_exception)?;\n            if !defined {{\n                return Err(JsError::type_error(\"the dictionary member cannot be defined\"));\n            }}\n        }}\n",
            member.name
        );
    }
    out.push_str("        Ok(object.into())\n    }\n}\n");
}

fn dictionary_quickjs(
    members: &[&DictionaryMember],
    conversion_members: &[&DictionaryMember],
    name: &str,
    out: &mut String,
) {
    // The QuickJS arm's counterpart of `dictionary_v8`'s missing-argument rule:
    // a dictionary the caller passed no object for converts to its default, and
    // that is only sound when nothing in it is required. QuickJS has no separate
    // "undefined object" case to fall through to, so a dictionary with a required
    // member reports the missing one it checks first.
    let delegate = if members.iter().any(|member| member.required) {
        format!(
            "            return Err(rquickjs::Exception::throw_type(\n                ctx,\n                \"`{name}` requires an object\",\n            ));\n"
        )
    } else {
        "            return Ok(result);\n".to_owned()
    };
    let _ = write!(
        out,
        "\n#[cfg(feature = \"quickjs\")]\nimpl<'js> rquickjs::FromJs<'js> for {name} {{\n    \
         fn from_js(ctx: &rquickjs::Ctx<'js>, value: rquickjs::Value<'js>) -> rquickjs::Result<Self> {{\n        \
         let mut result = Self::default();\n        \
         if !value.is_object() && !value.is_null() && !value.is_undefined() {{ return Err(rquickjs::Exception::throw_type(ctx, \"dictionary requires an object\")); }}\n        let Some(object) = value.as_object() else {{\n{delegate}        }};\n"
    );
    for member in conversion_members {
        let conversion = super::quickjs::from_value(&member.ty, "ctx", "member");
        let conversion =
            convert::legacy_null_to_empty(&member.ty, &member.attrs, "member", conversion);
        let assign = if member.required || member.default.is_some() {
            format!("result.{} = member;", member.rust_name)
        } else {
            format!("result.{} = Some(member);", member.rust_name)
        };
        let _ = write!(
            out,
            "        let member: rquickjs::Value = object.get(\"{}\")?;\n        if !member.is_undefined() {{\n            let member = {conversion}?;\n            {assign}\n        }}",
            member.name
        );
        if member.required {
            let _ = write!(
                out,
                " else {{\n            return Err(rquickjs::Exception::throw_type(\n                ctx,\n                \"`{name}` requires the member `{}`\",\n            ));\n        }}",
                member.name
            );
        }
        out.push('\n');
    }
    out.push_str("        Ok(result)\n    }\n}\n");

    let _ = write!(
        out,
        "\n#[cfg(feature = \"quickjs\")]\nimpl<'js> rquickjs::IntoJs<'js> for {name} {{\n    \
         fn into_js(self, ctx: &rquickjs::Ctx<'js>) -> rquickjs::Result<rquickjs::Value<'js>> {{\n        \
         let object = rquickjs::Object::new(ctx.clone())?;\n"
    );
    for member in conversion_members {
        let conversion = super::quickjs::to_value(&member.ty, "ctx", "member");
        if !member.required && member.default.is_none() {
            let _ = writeln!(
                out,
                "        if let Some(member) = self.{} {{\n            let value = ({conversion})?;\n            object.prop(\"{}\", rquickjs::object::Property::from(value).writable().enumerable().configurable())?;\n        }}",
                member.rust_name, member.name
            );
        } else {
            let _ = writeln!(
                out,
                "        {{\n            let member = self.{};\n            let value = ({conversion})?;\n            object.prop(\"{}\", rquickjs::object::Property::from(value).writable().enumerable().configurable())?;\n        }}",
                member.rust_name, member.name
            );
        }
    }
    out.push_str("        Ok(object.into_value())\n    }\n}\n");
}

/// `self.field` for `Copy` types, `self.field.clone()` otherwise.
fn field_expr(ty: &Type, path: &str) -> String {
    if is_copy(ty) {
        path.to_string()
    } else {
        format!("{path}.clone()")
    }
}

fn is_copy(ty: &Type) -> bool {
    match ty {
        Type::DomString
        | Type::UsvString
        | Type::ByteString
        | Type::Buffer(_)
        | Type::Dictionary(_)
        | Type::Union(_)
        | Type::Sequence(_)
        | Type::FrozenArray(_)
        | Type::ObservableArray(_)
        | Type::Record(_, _) => false,
        Type::Nullable(inner) => is_copy(inner),
        _ => true,
    }
}

fn union_code(union: &Union, out: &mut String) {
    let name = &union.name;
    let idl = union
        .members
        .iter()
        .map(|m| m.ty.idl_name())
        .collect::<Vec<_>>()
        .join(" or ");
    let _ = write!(
        out,
        "\n/// WebIDL `({idl})`.\n#[derive(Debug, Clone, PartialEq)]\npub enum {name} {{\n"
    );
    for member in &union.members {
        let _ = write!(
            out,
            "    /// `{}`\n    {}({}),\n",
            member.ty.idl_name(),
            member.rust_name,
            rust_type(&member.ty, Position::Owned),
        );
    }
    out.push_str("}\n");

    let _ = write!(
        out,
        "\n#[cfg(feature = \"v8\")]\nimpl {name} {{\n    \
         /// Converts a JavaScript value to this union.\n    \
         ///\n    \
         /// Tested arms keep declaration order except callback interfaces follow\n    \
         /// callable, platform, buffer and iterable arms. A sequence uses\n    \
         /// `@@iterator`; the first arm without a test\n    \
         /// is the fallback.\n    \
         pub fn from_v8<'s>(\n        scope: &mut v8::PinScope<'s, '_>,\n        value: v8::Local<'s, v8::Value>,\n    ) -> Result<Self, JsError> {{\n"
    );
    // WebIDL's first step for a union: `null` and `undefined` are the
    // dictionary arm's, when there is one, and convert to its default.
    if let Some(member) = union_dictionary_member(union) {
        let conversion = convert::from_v8(&member.ty, "scope", "value", IntegerMode::Modulo);
        let _ = write!(
            out,
            "        if value.is_null_or_undefined() {{\n            return ({conversion}).map({name}::{});\n        }}\n",
            member.rust_name
        );
    }
    let mut fallback: Option<String> = None;
    for member in union_conversion_members(union) {
        // Interface selection is one operation: it validates the native V8
        // template brand and obtains the wrapper's handle. A separate boolean
        // test would either repeat that lookup during conversion or accept a
        // prototype-chain holder that is not itself a platform wrapper.
        if let Type::Interface(interface) = &member.ty {
            let _ = write!(
                out,
                "        if let Some(inner) = interface_handle_from_v8::<{interface}>(scope, value)? {{\n            return Ok({name}::{}(inner));\n        }}\n",
                member.rust_name
            );
            continue;
        }
        // A string fallback still runs after every distinguishing test. Its
        // fallible `ToString` leaves the page's original exception pending.
        let conversion = convert::from_v8(&member.ty, "scope", "value", IntegerMode::Modulo);
        let test = union_test(&member.ty);
        match test {
            Some(test) => {
                let _ = write!(
                    out,
                    "        if {test} {{\n            return ({conversion}).map({name}::{});\n        }}\n",
                    member.rust_name
                );
            }
            // The fallback is the *first* arm without a test, so an arm the
            // union declares early is never shadowed by a later one of the
            // same kind; the last test-less member used to win instead, which
            // left `(record<K, V> or DOMString)` stringifying every object.
            None => {
                fallback.get_or_insert_with(|| {
                    format!("        ({conversion}).map({name}::{})\n", member.rust_name)
                });
            }
        }
    }
    // WebIDL's last steps: a value no test selected converts through the
    // numeric arm when the union has one, and through the boolean arm
    // otherwise, so `(AddEventListenerOptions or boolean)` given `1` is `true`.
    if fallback.is_none()
        && let Some(member) = union_last_resort_member(union)
    {
        let conversion = convert::from_v8(&member.ty, "scope", "value", IntegerMode::Modulo);
        fallback = Some(format!(
            "        ({conversion}).map({name}::{})\n",
            member.rust_name
        ));
    }
    match fallback {
        Some(text) => out.push_str(&text),
        None => {
            // The message names the union, so that a page's failure says which
            // argument it was.
            let _ = writeln!(
                out,
                "        Err(JsError::type_error(\"the value is not of type '({idl})'\"))"
            );
        }
    }
    out.push_str("    }\n\n    /// Converts this union to a JavaScript value.\n    pub fn to_v8<'s>(\n        &self,\n        scope: &mut v8::PinScope<'s, '_>,\n    ) -> Result<v8::Local<'s, v8::Value>, JsError> {\n        match self {\n");
    for member in &union.members {
        let owned = if is_copy(&member.ty) {
            "*inner".to_string()
        } else {
            "inner.clone()".to_string()
        };
        let conversion = convert::to_v8(&member.ty, "scope", "value");
        let _ = write!(
            out,
            "            {name}::{}(inner) => {{\n                let value = {owned};\n                {conversion}\n            }}\n",
            member.rust_name
        );
    }
    out.push_str("        }\n    }\n}\n");

    let _ = write!(
        out,
        "\n#[cfg(feature = \"quickjs\")]\nimpl<'js> rquickjs::FromJs<'js> for {name} {{\n    \
         fn from_js(ctx: &rquickjs::Ctx<'js>, value: rquickjs::Value<'js>) -> rquickjs::Result<Self> {{\n"
    );
    if let Some(member) = union_dictionary_member(union) {
        let conversion = super::quickjs::from_value(&member.ty, "ctx", "value");
        let _ = write!(
            out,
            "        if value.is_null() || value.is_undefined() {{\n            return {conversion}.map({name}::{});\n        }}\n",
            member.rust_name
        );
    }
    let mut qjs_fallback: Option<String> = None;
    for member in union_conversion_members(union) {
        let conversion = super::quickjs::from_value(&member.ty, "ctx", "value");
        match union_test_quickjs(&member.ty) {
            Some(test) => {
                let _ = write!(
                    out,
                    "        if {test} {{\n            return {conversion}.map({name}::{});\n        }}\n",
                    member.rust_name
                );
            }
            None => {
                qjs_fallback.get_or_insert_with(|| {
                    format!("        {conversion}.map({name}::{})\n", member.rust_name)
                });
            }
        }
    }
    if qjs_fallback.is_none()
        && let Some(member) = union_last_resort_member(union)
    {
        let conversion = super::quickjs::from_value(&member.ty, "ctx", "value");
        qjs_fallback = Some(format!(
            "        {conversion}.map({name}::{})\n",
            member.rust_name
        ));
    }
    match qjs_fallback {
        Some(text) => out.push_str(&text),
        None => {
            let _ = writeln!(
                out,
                "        Err(rquickjs::Exception::throw_type(ctx, \"the value is not of type '({idl})'\"))"
            );
        }
    }
    out.push_str("    }\n}\n");

    let _ = write!(
        out,
        "\n#[cfg(feature = \"quickjs\")]\nimpl<'js> rquickjs::IntoJs<'js> for {name} {{\n    \
         fn into_js(self, ctx: &rquickjs::Ctx<'js>) -> rquickjs::Result<rquickjs::Value<'js>> {{\n        match self {{\n"
    );
    for member in &union.members {
        let conversion = super::quickjs::to_value(&member.ty, "ctx", "inner");
        let _ = writeln!(
            out,
            "            {name}::{}(inner) => {conversion},",
            member.rust_name
        );
    }
    out.push_str("        }\n    }\n}\n");
}

/// A callback interface accepts any object, so it must not claim a callable,
/// platform object, buffer or iterable before WebIDL's earlier union steps.
/// Preserve declaration order among the other arms and keep the callback
/// interface as the last tested object arm. String fallbacks remain last.
/// The union's dictionary arm, which `null` and `undefined` convert to
/// (<https://webidl.spec.whatwg.org/#es-union>, step 1).
fn union_dictionary_member(union: &Union) -> Option<&UnionMember> {
    union
        .members
        .iter()
        .find(|member| matches!(&member.ty, Type::Dictionary(_)))
}

/// The arm a value converts through once no test has selected one and the
/// union has no string arm: the numeric arm when there is one, else the
/// boolean arm (the same algorithm, steps 18 and 19).
fn union_last_resort_member(union: &Union) -> Option<&UnionMember> {
    let numeric = |member: &&UnionMember| {
        member.ty.is_integer() || matches!(&member.ty, Type::Float { .. } | Type::Double { .. })
    };
    union.members.iter().find(numeric).or_else(|| {
        union
            .members
            .iter()
            .find(|member| matches!(&member.ty, Type::Boolean))
    })
}

fn union_conversion_members(union: &Union) -> impl Iterator<Item = &UnionMember> {
    union
        .members
        .iter()
        .filter(|member| !matches!(&member.ty, Type::CallbackInterface(_)))
        .chain(
            union
                .members
                .iter()
                .filter(|member| matches!(&member.ty, Type::CallbackInterface(_))),
        )
}

/// The V8 predicate that selects a union arm, or `None` for the fallback arm.
///
/// A sequence is selected through `@@iterator`, the `Get` WebIDL's conversion
/// performs, so any iterable and not only an array qualifies. A record is
/// selected as the object that is left once the sequence arm has declined; the
/// corpus declares the sequence arm first, which is the order WebIDL's own
/// conversion algorithm uses for object values. A buffer source is selected by
/// the class the runtime conversion brand-checks; see `buffer_union_test`.
fn union_test(ty: &Type) -> Option<&'static str> {
    match ty {
        Type::Interface(_) => unreachable!("interface arms have their own handle test"),
        Type::Object | Type::Dictionary(_) => Some("value.is_object()"),
        // WebIDL gates its sequence and record arms on `V` being an *object*:
        // a string primitive has a `@@iterator` of its own, and probing for it
        // without the gate would turn `new URLSearchParams('a=1')` into the
        // sequence arm's `[['a'], ['='], ['1']]` instead of three minus one
        // form-encoded pairs.
        Type::Sequence(_) | Type::FrozenArray(_) | Type::ObservableArray(_) => {
            Some("value.is_object() && has_iterator(scope, value)?")
        }
        Type::Record(_, _) => Some("value.is_object() && !value.is_array()"),
        Type::Buffer(kind) => Some(buffer_union_test(*kind)),
        Type::Boolean => Some("value.is_boolean()"),
        Type::Callback(_) => Some("value.is_function()"),
        Type::CallbackInterface(_) => Some("value.is_object()"),
        Type::Symbol => Some("value.is_symbol()"),
        ty if ty.is_integer() => Some("value.is_number()"),
        Type::Float { .. } | Type::Double { .. } => Some("value.is_number()"),
        _ => None,
    }
}

/// The V8 predicate that selects a buffer source union arm.
///
/// The test names the class the runtime conversion brand-checks. Without it the
/// arm has no discriminating test at all, which makes it the union's fallback or
/// drops it: `typedef (BufferSource or USVString) BodyInit;` would convert every
/// argument through the `USVString` arm and stringify a typed array to `"1,2"`
/// instead of taking its bytes.
///
/// `ArrayBuffer` and `BufferSource` admit a `SharedArrayBuffer`, because
/// WebIDL's `ArrayBuffer` type is an object with an `[[ArrayBufferData]]`
/// internal slot and a `SharedArrayBuffer` has that slot too — WebIDL tells the
/// two apart only through its `[AllowShared]` extended attribute, which no
/// declaration here can carry: weedle 0.4 has no `SharedArrayBuffer` keyword, so
/// `AllowSharedBufferSource` is unwritable (`docs/dev/idl.md`). The runtime
/// conversions brand-check the class and refuse a bare `SharedArrayBuffer` with
/// a `TypeError`; selecting the arm for one keeps that `TypeError` instead of
/// letting the value fall past the arm and be silently stringified.
///
/// The typed arrays are matched per class rather than through
/// `is_array_buffer_view()`: WebIDL selects the `Uint8Array` arm only for an
/// object whose `[[TypedArrayName]]` is `"Uint8Array"`, so the specific
/// predicate is the faithful one.
fn buffer_union_test(kind: BufferType) -> &'static str {
    match kind {
        BufferType::ArrayBuffer => "value.is_array_buffer() || value.is_shared_array_buffer()",
        BufferType::DataView => "value.is_data_view()",
        BufferType::Int8Array => "value.is_int8_array()",
        BufferType::Int16Array => "value.is_int16_array()",
        BufferType::Int32Array => "value.is_int32_array()",
        BufferType::Uint8Array => "value.is_uint8_array()",
        BufferType::Uint16Array => "value.is_uint16_array()",
        BufferType::Uint32Array => "value.is_uint32_array()",
        BufferType::Uint8ClampedArray => "value.is_uint8_clamped_array()",
        BufferType::Float32Array => "value.is_float32_array()",
        BufferType::Float64Array => "value.is_float64_array()",
        BufferType::ArrayBufferView => "value.is_array_buffer_view()",
        BufferType::BufferSource => {
            "value.is_array_buffer() || value.is_shared_array_buffer() || value.is_array_buffer_view()"
        }
    }
}

/// The QuickJS predicate that selects a union arm, or `None` for the fallback.
///
/// Interface and buffer arms inspect native brands. Sequence arms probe the
/// iterator protocol consumed by `quickjs_sequence`; ordinary objects remain
/// eligible for the record arm.
fn union_test_quickjs(ty: &Type) -> Option<String> {
    Some(match ty {
        Type::Interface(name) => format!("quickjs_is_interface(ctx, &value, {name:?})"),
        Type::Object | Type::Dictionary(_) => "value.is_object()".into(),
        Type::Sequence(_) | Type::FrozenArray(_) | Type::ObservableArray(_) => {
            "quickjs_has_iterator(ctx, &value)?".into()
        }
        Type::Record(_, _) => "value.is_object()".into(),
        Type::Buffer(kind) => format!("quickjs_is_buffer(&value, {:?})", kind.idl_name()),
        Type::Boolean => "value.is_bool()".into(),
        Type::Callback(_) => "value.is_function()".into(),
        Type::CallbackInterface(_) => "value.is_object()".into(),
        Type::Symbol => "value.is_symbol()".into(),
        ty if ty.is_integer() => "value.is_number()".into(),
        Type::Float { .. } | Type::Double { .. } => "value.is_number()".into(),
        _ => return None,
    })
}

fn callbacks(model: &Model, out: &mut String) {
    if model.callbacks.is_empty() && model.callback_interfaces.is_empty() {
        return;
    }
    out.push_str("\n// Callback types. `Callback<Args, Ret>` is an opaque handle to a JavaScript\n// callable; `Args` is the argument tuple and `Ret` the return type.\n");
    for callback in &model.callbacks {
        let args = tuple_of(
            &callback
                .arguments
                .iter()
                .map(|a| a.ty.clone())
                .collect::<Vec<_>>(),
        );
        let ret = rust_type(&callback.return_type, Position::Owned);
        let idl_args = callback
            .arguments
            .iter()
            .map(|a| format!("{} {}", a.ty.idl_name(), a.name))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = write!(
            out,
            "\n/// `callback {} = {} ({idl_args});`\npub type {} = Callback<{args}, {ret}>;\n",
            callback.name,
            callback.return_type.idl_name(),
            callback.name,
        );
    }
    for interface in &model.callback_interfaces {
        let args = tuple_of(
            &interface
                .operation
                .arguments
                .iter()
                .map(|a| a.ty.clone())
                .collect::<Vec<_>>(),
        );
        let ret = rust_type(&interface.operation.return_type, Position::Owned);
        let _ = write!(
            out,
            "\n/// `callback interface {}` with the single operation `{}`.\npub type {} = Callback<{args}, {ret}>;\n",
            interface.name, interface.operation_name, interface.name,
        );
    }
}

fn tuple_of(types: &[Type]) -> String {
    if types.is_empty() {
        return "()".to_string();
    }
    let mut parts: Vec<String> = types
        .iter()
        .map(|ty| rust_type(ty, Position::Owned))
        .collect();
    if parts.len() == 1 {
        parts.push(String::new());
        return format!("({},)", parts[0]);
    }
    format!("({})", parts.join(", "))
}
