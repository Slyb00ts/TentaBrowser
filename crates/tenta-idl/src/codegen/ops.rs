//! The `*Ops` traits: the Rust view a host type implements for one interface.

use std::fmt::Write as _;

use crate::codegen::rust_type::{Position, float_literal, rust_type};
use crate::model::{
    Argument, Attribute, ConstValue, Constant, ExtendedAttributes, FastApi, Interface, Member,
    Model, Namespace, Operation, OperationGroup, Type,
};

/// Generates `<snake>_ops.rs` for an interface.
pub fn interface_ops(model: &Model, interface: &Interface) -> String {
    let name = &interface.name;
    let mut out = String::new();
    let chain = model.prototype_chain(name).join(" -> ");
    let exposure = interface.exposure.names().join(", ");
    let _ = write!(
        out,
        "// The `{name}Ops` trait. Generated by `tenta-idl`; do not edit.\n\
         //\n\
         // Prototype chain: `{chain}`.\n\
         // Exposed: `{exposure}`.\n"
    );
    if !interface.included_mixins.is_empty() {
        let _ = writeln!(
            out,
            "// Includes: {}.",
            interface.included_mixins.join(", ")
        );
    }
    if interface.partial_blocks > 0 {
        let _ = writeln!(
            out,
            "// Merged `partial interface` blocks: {}.",
            interface.partial_blocks
        );
    }

    let supertrait = match &interface.parent {
        Some(parent) if model.interface(parent).is_some() => format!(": {parent}Ops"),
        _ => String::new(),
    };
    let _ = write!(
        out,
        "\n/// The host side of the WebIDL interface `{name}`.\n\
         ///\n\
         /// Fast-API eligible members (`docs/spec/05-javascript.md` §2) return their\n\
         /// value directly; every other member returns `Result<_, JsError>` so the\n\
         /// glue can turn a failure into a JavaScript exception.\n\
         pub trait {name}Ops{supertrait} {{\n"
    );

    let mut first = true;
    for constant in &interface.constants {
        separate(&mut out, &mut first);
        constant_item(constant, &mut out);
    }
    for member in &interface.members {
        match member {
            Member::Attribute(attribute) => {
                separate(&mut out, &mut first);
                attribute_items(attribute, &mut out);
            }
            Member::Operation(group) => {
                for overload in &group.overloads {
                    separate(&mut out, &mut first);
                    operation_item(group, overload, &mut out);
                }
            }
        }
    }
    for overload in &interface.special_operations {
        separate(&mut out, &mut first);
        let group = OperationGroup {
            name: String::new(),
            is_static: false,
            overloads: Vec::new(),
            fast: FastApi::Eligible,
            origin: crate::model::MemberOrigin::Interface,
        };
        operation_item(&group, overload, &mut out);
    }
    if let Some(iterable) = &interface.iterable
        && let Some(key) = &iterable.key
        && !iterable.is_async
    {
        separate(&mut out, &mut first);
        pair_iterator_item(key, &iterable.value, &mut out);
    }
    out.push_str("}\n");

    if !interface.constructors.is_empty() {
        constructor_trait(interface, &mut out);
    }
    out
}

/// Generates `<snake>_ops.rs` for a namespace.
pub fn namespace_ops(_model: &Model, namespace: &Namespace) -> String {
    let name = &namespace.name;
    let mut out = String::new();
    let exposure = namespace.exposure.names().join(", ");
    let _ = write!(
        out,
        "// The `{name}Ops` trait. Generated by `tenta-idl`; do not edit.\n\
         //\n\
         // `namespace {name}` has no prototype chain and no instances; every member\n\
         // is reached through the namespace object.\n\
         // Exposed: `{exposure}`.\n"
    );
    if namespace.partial_blocks > 0 {
        let _ = writeln!(
            out,
            "// Merged `partial namespace` blocks: {}.",
            namespace.partial_blocks
        );
    }
    let _ = write!(
        out,
        "\n/// The host side of the WebIDL namespace `{name}`.\npub trait {name}Ops {{\n"
    );
    let mut first = true;
    for constant in &namespace.constants {
        separate(&mut out, &mut first);
        constant_item(constant, &mut out);
    }
    for member in &namespace.members {
        match member {
            Member::Attribute(attribute) => {
                separate(&mut out, &mut first);
                attribute_items(attribute, &mut out);
            }
            Member::Operation(group) => {
                for overload in &group.overloads {
                    separate(&mut out, &mut first);
                    operation_item(group, overload, &mut out);
                }
            }
        }
    }
    out.push_str("}\n");
    out
}

fn separate(out: &mut String, first: &mut bool) {
    if *first {
        *first = false;
    } else {
        out.push('\n');
    }
}

fn constant_item(constant: &Constant, out: &mut String) {
    let ty = rust_type(&constant.ty, Position::Owned);
    let value = match &constant.value {
        ConstValue::Boolean(value) => value.to_string(),
        ConstValue::Integer(value) => value.to_string(),
        ConstValue::Float(value) => float_literal(*value),
        ConstValue::Null => "0".to_string(),
    };
    let _ = write!(
        out,
        "    /// `const {} {} = {value};`\n    const {}: {ty} = {value};\n",
        constant.ty.idl_name(),
        constant.name,
        constant.rust_name,
    );
}

fn attribute_items(attribute: &Attribute, out: &mut String) {
    let receiver = if attribute.is_static { "" } else { "&self" };
    let declaration = attribute_declaration(attribute);
    let getter_type = rust_type(&attribute.ty, Position::Owned);
    let getter_return = match attribute.fast_getter {
        FastApi::Eligible => format!(" -> {getter_type}"),
        FastApi::Ineligible(_) => format!(" -> Result<{getter_type}, JsError>"),
    };
    let _ = writeln!(out, "    /// `{declaration}`");
    write_fast_note(out, attribute.fast_getter, "getter");
    write_origin(out, attribute);
    let _ = writeln!(
        out,
        "    fn {}({receiver}){getter_return};",
        attribute.getter_name
    );

    let (Some(setter_name), Some(fast_setter)) = (&attribute.setter_name, attribute.fast_setter)
    else {
        return;
    };
    let setter_type = rust_type(&attribute.ty, Position::Argument);
    let setter_return = match fast_setter {
        FastApi::Eligible => String::new(),
        FastApi::Ineligible(_) => " -> Result<(), JsError>".to_string(),
    };
    let comma = if receiver.is_empty() { "" } else { ", " };
    let _ = write!(out, "\n    /// Setter for `{}`.\n", attribute.name);
    write_fast_note(out, fast_setter, "setter");
    let _ = writeln!(
        out,
        "    fn {setter_name}({receiver}{comma}value: {setter_type}){setter_return};"
    );
}

fn write_fast_note(out: &mut String, fast: FastApi, what: &str) {
    match fast {
        FastApi::Eligible => {
            let _ = write!(
                out,
                "    ///\n    /// V8 fast API: the {what} is eligible.\n"
            );
        }
        FastApi::Ineligible(reason) => {
            let _ = write!(
                out,
                "    ///\n    /// V8 fast API: the {what} is not eligible ({reason}).\n"
            );
        }
    }
}

fn write_origin(out: &mut String, attribute: &Attribute) {
    if let crate::model::MemberOrigin::Mixin(mixin) = &attribute.origin {
        let _ = write!(
            out,
            "    ///\n    /// Included from `interface mixin {mixin}`.\n"
        );
    }
}

fn operation_item(group: &OperationGroup, operation: &Operation, out: &mut String) {
    let receiver = if group.is_static { "" } else { "&self" };
    let mut parameters: Vec<String> = Vec::new();
    if !receiver.is_empty() {
        parameters.push(receiver.to_string());
    }
    for argument in &operation.arguments {
        parameters.push(format!(
            "{}: {}",
            argument.rust_name,
            argument_type(argument)
        ));
    }
    let return_type = rust_type(&operation.return_type, Position::Owned);
    let return_clause = match operation.fast {
        FastApi::Eligible if operation.return_type == Type::Undefined => String::new(),
        FastApi::Eligible => format!(" -> {return_type}"),
        FastApi::Ineligible(_) => format!(" -> Result<{return_type}, JsError>"),
    };
    let _ = writeln!(out, "    /// `{}`", operation_declaration(operation));
    if group.overloads.len() > 1 {
        let _ = write!(
            out,
            "    ///\n    /// Overload {} of {} for `{}`.\n",
            group
                .overloads
                .iter()
                .position(|o| o.rust_name == operation.rust_name)
                .map(|index| index + 1)
                .unwrap_or(1),
            group.overloads.len(),
            group.name,
        );
    }
    write_fast_note(out, operation.fast, "operation");
    if let crate::model::MemberOrigin::Mixin(mixin) = &group.origin {
        let _ = write!(
            out,
            "    ///\n    /// Included from `interface mixin {mixin}`.\n"
        );
    }
    let _ = writeln!(
        out,
        "    fn {}({}){return_clause};",
        operation.rust_name,
        parameters.join(", ")
    );
}

/// The single host hook a pair iterator needs.
///
/// `iterable<K, V>` has no indexed accessor to drive an iterator from — the
/// spec gives neither `Headers` nor `URLSearchParams` a `length` — so the host
/// hands over a snapshot of the whole collection instead. Each of the three
/// generated members (`entries`, `keys`, `values`) is a view over that one
/// snapshot, which is what keeps the type atomic across a live collection.
fn pair_iterator_item(key: &Type, value: &Type, out: &mut String) {
    let key_type = rust_type(key, Position::Owned);
    let value_type = rust_type(value, Position::Owned);
    let _ = write!(
        out,
        "    /// `iterable<{}, {}>;`\n    ///\n    /// A snapshot of the entries, in iteration order. The generated\n    /// `entries`, `keys` and `values` members are views over one call, so a\n    /// collection mutated between two of them cannot be observed half-way.\n    fn iterable_entries(&self) -> Result<IterableEntries<{key_type}, {value_type}>, JsError>;\n",
        key.idl_name(),
        value.idl_name(),
    );
}

fn constructor_trait(interface: &Interface, out: &mut String) {
    let name = &interface.name;
    let _ = write!(
        out,
        "\n/// The constructor of `{name}`, kept apart from `{name}Ops` so that a\n\
         /// derived interface does not inherit a constructor its IDL does not declare.\n\
         pub trait {name}Constructor: {name}Ops + Sized {{\n"
    );
    for (index, constructor) in interface.constructors.iter().enumerate() {
        if index > 0 {
            out.push('\n');
        }
        let arguments = constructor
            .arguments
            .iter()
            .map(|a| format!("{}: {}", a.rust_name, argument_type(a)))
            .collect::<Vec<_>>()
            .join(", ");
        let idl_arguments = constructor
            .arguments
            .iter()
            .map(argument_declaration)
            .collect::<Vec<_>>()
            .join(", ");
        // The realm (host context) is threaded in as the first parameter so a
        // constructor can reach the document and event slab; the generated V8
        // callback pulls it from the isolate's wrapper world.
        let parameters = if arguments.is_empty() {
            "realm: &Realm".to_owned()
        } else {
            format!("realm: &Realm, {arguments}")
        };
        let _ = write!(
            out,
            "    /// `constructor({idl_arguments});`\n    fn {}({parameters}) -> Result<Self, JsError>;\n",
            constructor.rust_name
        );
    }
    out.push_str("}\n");
}

/// The Rust type of an argument, taking `optional` and `T...` into account.
pub fn argument_type(argument: &Argument) -> String {
    if argument.variadic {
        return format!("Vec<{}>", rust_type(&argument.ty, Position::Owned));
    }
    let base = rust_type(&argument.ty, Position::Argument);
    if argument.optional {
        format!("Option<{base}>")
    } else {
        base
    }
}

fn attribute_declaration(attribute: &Attribute) -> String {
    let mut text = String::new();
    push_ext_attrs(&mut text, &attribute.attrs);
    if attribute.is_static {
        text.push_str("static ");
    }
    if attribute.stringifier {
        text.push_str("stringifier ");
    }
    if attribute.inherit {
        text.push_str("inherit ");
    }
    if attribute.readonly {
        text.push_str("readonly ");
    }
    let _ = write!(
        text,
        "attribute {} {};",
        attribute.ty.idl_name(),
        attribute.name
    );
    text
}

fn operation_declaration(operation: &Operation) -> String {
    let mut text = String::new();
    push_ext_attrs(&mut text, &operation.attrs);
    if operation.stringifier {
        text.push_str("stringifier ");
    }
    if let Some(special) = operation.special {
        text.push_str(match special {
            crate::model::Special::Getter => "getter ",
            crate::model::Special::Setter => "setter ",
            crate::model::Special::Deleter => "deleter ",
            crate::model::Special::LegacyCaller => "legacycaller ",
        });
    }
    let arguments = operation
        .arguments
        .iter()
        .map(argument_declaration)
        .collect::<Vec<_>>()
        .join(", ");
    let _ = write!(
        text,
        "{} {}({arguments});",
        operation.return_type.idl_name(),
        operation.name
    );
    text
}

fn argument_declaration(argument: &Argument) -> String {
    let mut text = String::new();
    push_ext_attrs(&mut text, &argument.attrs);
    if argument.optional {
        text.push_str("optional ");
    }
    text.push_str(&argument.ty.idl_name());
    if argument.variadic {
        text.push_str("...");
    }
    let _ = write!(text, " {}", argument.name);
    if let Some(default) = &argument.default {
        let _ = write!(text, " = {}", default_literal(default));
    }
    text
}

pub(crate) fn default_literal(default: &crate::model::DefaultValue) -> String {
    use crate::model::DefaultValue;
    match default {
        DefaultValue::Boolean(value) => value.to_string(),
        DefaultValue::Integer(value) => value.to_string(),
        DefaultValue::Float(value) => float_literal(*value),
        DefaultValue::String(value) => format!("\"{value}\""),
        DefaultValue::Null => "null".to_string(),
        DefaultValue::EmptySequence => "[]".to_string(),
        DefaultValue::EmptyDictionary => "{}".to_string(),
    }
}

fn push_ext_attrs(text: &mut String, attrs: &ExtendedAttributes) {
    if attrs.0.is_empty() {
        return;
    }
    let names = attrs
        .0
        .iter()
        .map(|attribute| match &attribute.value {
            crate::model::ExtendedAttributeValue::None => attribute.name.clone(),
            crate::model::ExtendedAttributeValue::Ident(value) => {
                format!("{}={value}", attribute.name)
            }
            crate::model::ExtendedAttributeValue::String(value) => {
                format!("{}=\"{value}\"", attribute.name)
            }
            crate::model::ExtendedAttributeValue::IdentList(values) => {
                format!("{}=({})", attribute.name, values.join(","))
            }
            crate::model::ExtendedAttributeValue::Wildcard => format!("{}=*", attribute.name),
            crate::model::ExtendedAttributeValue::Arguments { rhs, .. } => match rhs {
                Some(rhs) => format!("{}={rhs}(...)", attribute.name),
                None => format!("{}(...)", attribute.name),
            },
        })
        .collect::<Vec<_>>()
        .join(", ");
    let _ = write!(text, "[{names}] ");
}
