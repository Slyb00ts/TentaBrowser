//! The box tree: what style and DOM become before layout.
//!
//! Built by `BoxTree::build`, read by every layout algorithm. Boxes live in an
//! arena and refer to each other by [`BoxId`], so dropping a deep tree never
//! recurses.

use std::cell::Cell;
use std::ops::Range;
use std::sync::Arc;

use smallvec::SmallVec;
use tenta_core::NodeId;
use tenta_css::cascade::{Style, StyleEngine};
use tenta_dom::Document;

use crate::font::FontSystem;
use crate::types::{IntrinsicSize, MarkerKind, PaintStyle, ReplacedKind, TableKind};

/// Index of a [`LayoutBox`] in its [`BoxTree`].
#[derive(Copy, Clone, PartialEq, Eq, Hash, Debug)]
pub struct BoxId(pub u32);

impl BoxId {
    /// The parent of the root box, and the value of "no box".
    pub const NONE: BoxId = BoxId(u32::MAX);

    /// The arena index.
    pub fn index(self) -> usize {
        self.0 as usize
    }
}

bitflags::bitflags! {
    /// Facts about a box that layout algorithms branch on, derived once by the
    /// box-tree builder.
    #[derive(Copy, Clone, PartialEq, Eq, Debug, Default)]
    pub struct BoxFlags: u16 {
        /// Taken out of normal flow (floats and absolutely positioned boxes).
        const OUT_OF_FLOW = 1 << 0;
        /// `float` is not `none`.
        const FLOAT = 1 << 1;
        /// `position` is `absolute` or `fixed`.
        const ABSPOS = 1 << 2;
        /// Establishes a block formatting context.
        const ESTABLISHES_BFC = 1 << 3;
        /// A replaced element or form control.
        const REPLACED = 1 << 4;
        /// Participates in an inline formatting context.
        const INLINE_LEVEL = 1 << 5;
        /// Generated by `::before`, `::after` or `::marker`.
        const GENERATED = 1 << 6;
        /// Created by the builder, with no DOM node of its own.
        const ANONYMOUS = 1 << 7;
        /// A [`PaintStyle`] value depends on the box's used size (a percentage
        /// `translate`, or a `to <corner>` gradient direction). Layout asks
        /// [`BoxTree::paint_style_for`] for the style of each fragment.
        const PAINT_SIZE_DEPENDENT = 1 << 8;
        /// Some paint feature of the style has no `PaintStyle` representation
        /// yet (radial or conic gradients, `image-set()`, gradient hints, filter
        /// URLs, `background-clip: text`, 3D rotation) and was left out.
        const PAINT_SKIPPED = 1 << 9;
    }
}

/// What a box is and therefore which algorithm lays it out.
#[derive(Clone, PartialEq, Debug)]
pub enum BoxKind {
    /// A block container.
    Block,
    /// A block container that establishes an independent formatting context.
    FlowRoot,
    /// A list item; `marker` is the outside marker box when present.
    ListItem {
        /// The `::marker` box.
        marker: Option<BoxId>,
    },
    /// An anonymous block wrapping inline-level siblings of block boxes.
    AnonymousBlock,
    /// An `inline-block` atomic inline.
    InlineBlock,
    /// An inline box. Exists only as the target of
    /// [`InlineItem::OpenInline`] and [`InlineItem::CloseInline`].
    Inline,
    /// A replaced element or form control (placeholder content in M1).
    Replaced(ReplacedKind),
    /// A list marker.
    Marker(MarkerKind),
    /// A flex container, laid out as a block until flex layout exists.
    Flex,
    /// A grid container, laid out as a block until grid layout exists.
    Grid,
    /// A table part, laid out as a block until table layout exists.
    Table(TableKind),
}

/// Where the characters of an [`InlineItem::Text`] come from.
#[derive(Clone, PartialEq, Debug)]
pub enum TextSource {
    /// A byte range of a DOM text node's data.
    Node {
        /// The text node.
        node: NodeId,
        /// Byte range into the node's data.
        range: Range<u32>,
    },
    /// Text the box-tree builder generated: `::before`/`::after` content,
    /// list-marker strings and form-control values. The builder owns it.
    Owned(Arc<str>),
}

/// One entry of an inline formatting context, in tree order.
#[derive(Clone, PartialEq, Debug)]
pub enum InlineItem {
    /// A run of text.
    Text {
        /// The characters.
        source: TextSource,
        /// The inline or block box whose style applies to the text.
        style_box: BoxId,
    },
    /// Start of an inline box.
    OpenInline {
        /// The inline box.
        box_id: BoxId,
        /// This piece resumes a box that a block-level child interrupted, so it
        /// carries no start edge (margin, border, padding).
        resumes: bool,
    },
    /// End of an inline box.
    CloseInline {
        /// The inline box.
        box_id: BoxId,
        /// A block-level child interrupts the box here and it resumes later, so
        /// this piece carries no end edge.
        interrupted: bool,
    },
    /// An atomic inline: inline-block, inline-flex or replaced.
    Atomic {
        /// The atomic box.
        box_id: BoxId,
    },
    /// A forced line break (`<br>`).
    ForcedBreak {
        /// The `<br>` box.
        box_id: BoxId,
    },
    /// A soft wrap opportunity with no glyph (`<wbr>`).
    SoftBreak,
    /// Placeholder at a float's source position.
    Float {
        /// The float box.
        box_id: BoxId,
    },
    /// Placeholder for an absolutely positioned box's static position.
    AbsPos {
        /// The positioned box.
        box_id: BoxId,
    },
}

/// The inline-level content of one block container.
#[derive(Clone, PartialEq, Debug)]
pub struct InlineFormattingContext {
    /// Tree-order items; white space is not yet processed.
    pub items: Vec<InlineItem>,
    /// The block container owning this context.
    pub root: BoxId,
}

/// A node of the box tree.
#[derive(Debug)]
pub struct LayoutBox {
    /// Originating DOM node; [`NodeId::NONE`] for anonymous boxes.
    pub node: NodeId,
    /// Parent box; [`BoxId::NONE`] for the root.
    pub parent: BoxId,
    /// Box type.
    pub kind: BoxKind,
    /// Full computed style (anonymous boxes carry the inherited style).
    pub style: Style,
    /// Paint-relevant style, shared by every fragment of this box.
    pub paint: Arc<PaintStyle>,
    /// Derived facts.
    pub flags: BoxFlags,
    /// Block-level children; empty when `ifc` is set.
    pub children: SmallVec<[BoxId; 4]>,
    /// Set on block containers whose children are inline-level.
    pub ifc: Option<Box<InlineFormattingContext>>,
    /// Memoised `(min-content, max-content)` inline sizes. The tree is rebuilt
    /// when styles change, so the cache never outlives its inputs.
    pub intrinsic_inline: Cell<Option<(f32, f32)>>,
}

impl LayoutBox {
    /// A childless box with no flags and an empty intrinsic-size cache.
    pub fn new(
        node: NodeId,
        parent: BoxId,
        kind: BoxKind,
        style: Style,
        paint: Arc<PaintStyle>,
    ) -> Self {
        Self {
            node,
            parent,
            kind,
            style,
            paint,
            flags: BoxFlags::empty(),
            children: SmallVec::new(),
            ifc: None,
            intrinsic_inline: Cell::new(None),
        }
    }
}

/// The arena of boxes for one document.
#[derive(Debug)]
pub struct BoxTree {
    /// The root box (the initial containing block's child).
    pub root: BoxId,
    /// `Document::mutation_generation` when the tree was built.
    pub generation: u64,
    boxes: Vec<LayoutBox>,
    /// Indexed by DOM arena slot: a node can own a principal box plus
    /// `::before`, `::after` and `::marker` boxes.
    node_boxes: Vec<SmallVec<[BoxId; 1]>>,
}

impl BoxTree {
    /// An empty tree stamped with a document generation. The builder (and tests
    /// that hand-build trees) add boxes with [`BoxTree::push`].
    pub fn new(generation: u64) -> Self {
        Self {
            root: BoxId::NONE,
            generation,
            boxes: Vec::new(),
            node_boxes: Vec::new(),
        }
    }

    /// Adds a box and registers it under its node. The first box pushed
    /// becomes the root unless [`BoxTree::root`] is set explicitly.
    pub fn push(&mut self, b: LayoutBox) -> BoxId {
        let id = BoxId(self.boxes.len() as u32);
        if b.node.is_some() {
            let slot = b.node.raw() as usize;
            if self.node_boxes.len() <= slot {
                self.node_boxes.resize_with(slot + 1, SmallVec::new);
            }
            self.node_boxes[slot].push(id);
        }
        if self.root == BoxId::NONE {
            self.root = id;
        }
        self.boxes.push(b);
        id
    }

    /// The box with this id. Panics when the id is not from this tree.
    pub fn get(&self, id: BoxId) -> &LayoutBox {
        &self.boxes[id.index()]
    }

    /// Mutable access, for the builder fixing up parents and children.
    pub fn get_mut(&mut self, id: BoxId) -> &mut LayoutBox {
        &mut self.boxes[id.index()]
    }

    /// Number of boxes.
    pub fn len(&self) -> usize {
        self.boxes.len()
    }

    /// True when the tree holds no box.
    pub fn is_empty(&self) -> bool {
        self.boxes.is_empty()
    }

    /// The boxes a node generated, principal box first.
    pub fn boxes_of(&self, node: NodeId) -> &[BoxId] {
        self.node_boxes
            .get(node.raw() as usize)
            .map_or(&[], |boxes| boxes.as_slice())
    }
}

/// Intrinsic sizes of replaced content, by node. Implemented by the render
/// session once images load; [`NoImages`] answers for pages without them.
pub trait ImageInfo {
    /// Natural size of the image behind `node`, when known.
    fn intrinsic(&self, node: NodeId) -> Option<IntrinsicSize>;
}

/// An [`ImageInfo`] that knows no image.
#[derive(Copy, Clone, Default, Debug)]
pub struct NoImages;

impl ImageInfo for NoImages {
    fn intrinsic(&self, _node: NodeId) -> Option<IntrinsicSize> {
        None
    }
}

/// Everything layout may read or mutate, passed by `&mut`.
pub struct LayoutCx<'a> {
    /// The document being laid out.
    pub doc: &'a Document,
    /// Computed styles, already flushed for this document generation.
    pub styles: &'a StyleEngine,
    /// Shaping and font metrics.
    pub fonts: &'a mut FontSystem,
    /// Intrinsic sizes of replaced content.
    pub images: &'a dyn ImageInfo,
    /// Layout viewport in CSS pixels.
    pub viewport: (f32, f32),
    /// Quirks-mode layout rules apply (body fills the viewport, line-height
    /// strut).
    pub quirks: bool,
}
